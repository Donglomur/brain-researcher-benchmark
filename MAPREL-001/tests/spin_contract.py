"""Authenticate declared hemisphere-constrained spins, not a calibrated null spread."""
import numpy as np

VERSION = "spatial-geometry-v2"

def validate_spin(pa, pb, evidence, report, geometry, generator=None):
    assert str(geometry["schema_version"]) == VERSION, "genuine pinned surface geometry v2 required"
    assert report["null_family"] == "centroid_spin"
    assert report["spin_method"] in {"original","vasa","hungarian"}
    cent,hemi = np.asarray(evidence["centroids"]),np.asarray(evidence["hemisphere"])
    assert cent.shape == (len(pa),3) and hemi.shape == (len(pa),)
    assert np.allclose(cent,geometry["centroids"],atol=1e-7)
    assert np.array_equal(hemi,geometry["hemisphere"])
    assert set(hemi.tolist()) == {0,1}
    samples = np.asarray(evidence["spin_indices"])
    assert np.issubdtype(samples.dtype,np.integer)
    assert samples.shape == (len(pa),report["n_permutations"])
    assert 100 <= samples.shape[1] <= 4096 and samples.min()>=0 and samples.max()<len(pa)
    assert np.all(hemi[samples] == hemi[:,None]), "hemispheres mixed"
    if generator is None:
        from neuromaps.nulls.spins import gen_spinsamples
        generator = gen_spinsamples
    expected = generator(cent,hemi,n_rotate=samples.shape[1],
                         seed=report["seed"],method=report["spin_method"])
    assert np.array_equal(samples,expected), "indices are not generated by declared sphere rotation"
    null = np.array([np.corrcoef(np.asarray(pa)[samples[:,i]],pb)[0,1]
                     for i in range(samples.shape[1])])
    assert np.allclose(report["null_distribution"],null,atol=1e-6,rtol=0)
    observed=float(np.corrcoef(pa,pb)[0,1])
    p=float((1+np.count_nonzero(np.abs(null)>=abs(observed)))/(len(null)+1))
    assert np.isclose(report["p_spin"],p,atol=1e-6)
    assert report["significant_after_spatial_null"] is (p<.05)
    return p
