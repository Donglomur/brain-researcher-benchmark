def _verified_source_binding(here):
    """Read the literal accepted helper once and execute only its captured bytes."""
    if "source_binding" in sys.modules:
        raise ValueError("fresh source_binding module namespace required")
    path = Path(here) / "source_binding.py"
    if not path.is_absolute() or ".." in path.parts or any(x.is_symlink() for x in (path, *path.parents)):
        raise ValueError("ordinary bootstrap path")
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        before = os.fstat(fd)
        if not stat.S_ISREG(before.st_mode) or before.st_nlink != 1 or before.st_size != 4147:
            raise ValueError("bootstrap extent/type")
        with os.fdopen(fd, "rb", closefd=False) as stream:
            raw = stream.read(4148)
        stamp = lambda info: (info.st_dev, info.st_ino, info.st_mode, info.st_nlink,
                              info.st_size, info.st_mtime_ns, info.st_ctime_ns)
        if stamp(before) != stamp(os.fstat(fd)) or stamp(before) != stamp(path.lstat()):
            raise ValueError("bootstrap changed")
        if len(raw) != 4147 or hashlib.sha256(raw).hexdigest() != "1079a68cb275a35543f02dff2ad973ef2ae2e89b85c72fab9263d00eee89c3ce":
            raise ValueError("bootstrap identity")
    finally:
        os.close(fd)
    module = types.ModuleType("source_binding")
    module.__file__ = str(path)
    sys.modules["source_binding"] = module
    try:
        exec(compile(raw, str(path), "exec"), module.__dict__)
    except BaseException:
        if sys.modules.get("source_binding") is module:
            del sys.modules["source_binding"]
        raise
    return module


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lock-sha256", required=True)
    ap.add_argument("--work-deadline", required=True, type=float)
    args = ap.parse_args()
    here = Path(__file__).absolute().parent
    binding = _verified_source_binding(here)
    plan, lock, _, delivery, sources, _, modules = binding.load(args.lock_sha256)
    reuse, contract = modules["reuse_delivery"], modules["result_contract"]
    binding.need(os.getpid() == os.getpgrp(), "separately owned worker process group")
    binding.need(time.monotonic() < args.work_deadline <= time.monotonic() + plan["worker_seconds"],
                 "original outer-selected work deadline")
    signals, old = [], {}
    for sig in (signal.SIGTERM, signal.SIGINT, signal.SIGHUP):
        old[sig] = signal.signal(sig, lambda signum, frame: signals.append(signum))
    out = Path(plan["output"])
    started, family = time.monotonic(), None
    result = {"schema": "hybrid-no-refit-protected-operation-worker-v1", "status": "FAILED_PRESERVED",
        "error": None, "source_lock_sha256": args.lock_sha256, "new_fits": 0, "reused_folds": 0,
        "participant_campaign_run": False, "scientific_count_delta": 0,
        "outer_recovery_still_required": True, "participant_result": None, "reuse_receipt": None}
    try:
        cust = sources.modules["donor_checked_source"]
        lifecycle = sources.modules["donor_create_lifecycle"]
        closer = sources.modules["donor_process_closure"]
        Owner = sources.modules["episode_owner_base"].Owner
        sources.modules["endpoint_guard"].endpoint_identity(plan)
        preflight = out / "image-preflight"
        preflight.mkdir(mode=0o700)
        owner = Owner(cust, closer, preflight, sources.runner_root, plan, args.lock_sha256,
                      args.work_deadline, signals, plan["operation_token"],
                      lifecycle=lifecycle, cli_group_mode="controller")
        _, raw, _, _ = owner.call(["image", "inspect", "--format", "{{json .}}", plan["image"]])
        info = cust.strict(raw)
        binding.need(info["Id"] == plan["image"] and info["Os"] == "linux" and
                     info["Architecture"] == "arm64", "exact existing image; no pull")
        _, raw, _, _ = owner.call(["ps", "--all", "--quiet", "--no-trunc", "--filter",
                                  "label=hybrid.operation=" + plan["operation_token"]])
        binding.need(raw == b"", "fresh exclusive container namespace")
        # Key is generated by this trusted worker, retained separately for outer
        # verification, never mounted or sent through argv/participant output.
        secret = os.urandom(32)
        key_path = out / "CURATOR_KEY.private.bin"
        result["curator_key"] = dict(delivery._write_new(key_path, secret, 32), path=str(key_path))
        reuse_path = out / "HISTORICAL_REUSE.private.json"
        prepared = reuse.prepare_reused(sources, plan["cases"]["path"], plan["references"]["path"],
                                        out / "delivery", reuse_path, secret,
                                        artifact_locations=plan.get("historical_artifact_locations"))
        result["reuse_receipt"] = dict(prepared["reuse"], path=str(reuse_path))
        result["delivery_manifest"] = prepared["manifest"]
        result["reused_folds"] = prepared["reused_folds"]
        binding.need(not signals and time.monotonic() < args.work_deadline, "preparation within original horizon")
        reuse_snapshot = reuse.require_reuse(sources, reuse_path, prepared["reuse"], prepared["manifest"], secret,
                                              artifact_locations=plan.get("historical_artifact_locations"))
        family = sources.harness.EpisodeFamily(plan, sources.runner_root, out, args.work_deadline, signals)
        result["participant_campaign_run"] = True
        manifest_pin = (prepared["manifest"]["bytes"], prepared["manifest"]["sha256"])
        participant = delivery.run_authentic(sources, plan["cases"]["path"], plan["references"]["path"],
                                             out / "delivery", manifest_pin, secret, family)
        reuse_snapshot.check()
        sources.check()
        binding.recheck(lock)
        binding.need(not signals and time.monotonic() < args.work_deadline,
                     "complete 4,884 episodes before original horizon")
        result["participant_result"] = binding.emit(out / "PARTICIPANT_RESULT.private.json", participant, 16 * 1048576)
        result["participant_summary"] = participant["participant_result"]["score"]
        result["against_same_host_reference"] = participant["participant_result"]["against_same_host_reference"]
        result["status"] = contract.STATUS
    except BaseException as exc:
        result["error"] = {"type": type(exc).__name__, "reason": str(exc)[:2048]}
    finally:
        result["elapsed_seconds"] = time.monotonic() - started
        result["signals_received"] = signals
        result["episodes_registered"] = family.count if family is not None else 0
        result["all_registered_episodes_closed"] = (family is not None and len(family.rows) == family.count and
                                                   all(r["complete"] is True for r in family.rows))
        if result["status"] == contract.STATUS:
            try:
                contract.validate(result, args.lock_sha256)
            except BaseException as exc:
                result["status"] = "FAILED_PRESERVED"
                result["error"] = {"type": type(exc).__name__, "reason": str(exc)[:2048]}
        binding.emit(out / "RESULT.json", result)
        for sig, handler in old.items():
            signal.signal(sig, handler)
    print(json.dumps({"status": result["status"], "new_fits": 0, "no_retry": True}))
    return 0 if result["status"] == contract.STATUS else 1


if __name__ == "__main__":
    raise SystemExit(main())
