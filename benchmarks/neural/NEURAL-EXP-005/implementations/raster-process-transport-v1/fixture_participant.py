"""Owned generated protocol probe, NOT a neural model or prediction baseline."""

import base64
import hashlib
import json
import os
from pathlib import Path
import struct
import subprocess
import sys
import time
import zlib


def receive():
    return json.loads(sys.stdin.buffer.readline())


def send(value):
    sys.stdout.write(json.dumps(value, separators=(",", ":")) + "\n")
    sys.stdout.flush()


mode = sys.argv[1]
pages = int(sys.argv[2]) if len(sys.argv) > 2 else 1
assert "HELSINKI_PARENT_SECRET" not in os.environ
assert "PYTHONPATH" not in os.environ and "HOME" not in os.environ
assert not list(Path.cwd().iterdir())
assert globals().get("case_counter", 0) == 0
case_counter = 1
# One generated byte per invocation; the host must remove this owned case cwd.
Path("generated-memory-marker").write_bytes(b"1")
if len(sys.argv) > 3:
    try:
        os.fstat(int(sys.argv[3]))
    except OSError:
        pass
    else:
        raise AssertionError("inherited extra descriptor")

description = receive()
assert set(description) == {"schema", "binding", "sample_count", "montage", "sample_clock",
    "units", "duration_seconds", "prediction_interval_seconds", "quality_flags",
    "maximum_page_samples", "maximum_page_channels", "representation", "quality_flag_interpretation"}
assert description["schema"] == "helsinki-raster-description-v1"
assert description["duration_seconds"] == 30 and len(description["montage"]) == 18
assert description["prediction_interval_seconds"] == [29, 30]
assert len(description["quality_flags"]) == 30
binding = description["binding"]
assert set(binding) == {"case_id", "assessment_id", "protocol_id", "representation_sha256", "fold", "input_sha256"}
answer = {"action": "answer", "case_id": binding["case_id"],
          "input_sha256": binding["input_sha256"], "probability": 0.25}

if mode == "duplicate":
    sys.stdout.write('{"action":"describe","action":"describe"}\n'); sys.stdout.flush(); sys.exit(0)
if mode == "utf8":
    os.write(1, b"\xff\n"); sys.exit(0)
if mode == "partial":
    os.write(1, b'{"action":"describe"}'); sys.exit(0)
if mode == "oversize":
    os.write(1, b"x" * 1024 + b"\n"); sys.exit(0)
if mode == "two_frames":
    os.write(1, b'{"action":"describe"}\n{"action":"describe"}\n'); sys.exit(0)
if mode == "nonfinite":
    answer["probability"] = float("nan"); send(answer); sys.exit(0)
if mode == "wrong_binding":
    answer["case_id"] = "0" * 64; send(answer); sys.exit(0)
if mode == "unknown_action":
    send({"action": "read_file", "path": "/"}); sys.exit(0)
if mode == "future":
    send({"action": "view", "start_sample": description["sample_count"],
          "stop_sample": description["sample_count"] + 1, "channels": [0], "units_per_division": 20}); sys.exit(0)
if mode == "extra_field":
    send({"action": "describe", "samples": []}); sys.exit(0)
if mode == "hang_before":
    time.sleep(30); sys.exit(0)
if mode == "closed_input":
    os.close(0); send({"action": "describe"}); time.sleep(30); sys.exit(0)
if mode == "repeat":
    while True:
        send({"action": "describe"}); receive()

for page in range(pages):
    channels = list(range(page * 6, page * 6 + 6)) if pages == 3 else [0]
    send({"action": "view", "start_sample": 0, "stop_sample": description["sample_count"],
          "channels": channels, "units_per_division": 20})
    frame = receive()
    assert set(frame) == {"schema", "binding", "mime_type", "png_base64", "png_sha256", "width", "height",
        "selection", "clipped_sample_counts", "source_samples_visited_per_channel"}
    assert frame["schema"] == "helsinki-raster-frame-v1" and frame["binding"] == binding
    assert frame["mime_type"] == "image/png"
    png = base64.b64decode(frame["png_base64"], validate=True)
    assert png[:8] == b"\x89PNG\r\n\x1a\n" and hashlib.sha256(png).hexdigest() == frame["png_sha256"]
    offset, chunks = 8, []
    while offset < len(png):
        size = struct.unpack(">I", png[offset:offset + 4])[0]
        kind = png[offset + 4:offset + 8]; body = png[offset + 8:offset + 8 + size]
        crc = struct.unpack(">I", png[offset + 8 + size:offset + 12 + size])[0]
        assert zlib.crc32(kind + body) == crc
        chunks.append(kind); offset += size + 12
    assert chunks == [b"IHDR", b"IDAT", b"IEND"] and offset == len(png)
    assert frame["source_samples_visited_per_channel"] == description["sample_count"]
send(answer)
receipt = receive()
assert receipt == {"schema": "helsinki-raster-answer-receipt-v1", "accepted": True,
                   "case_id": binding["case_id"], "input_sha256": binding["input_sha256"]}
if mode == "after_answer":
    send(answer)
elif mode == "nonzero":
    sys.exit(7)
elif mode == "hang_after":
    time.sleep(30)
elif mode == "descendant":
    subprocess.Popen([sys.executable, "-I", "-S", "-B", "-c", "import time; time.sleep(30)"],
        stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
