def need(condition, message):
    if not condition:
        raise ValueError(message)


def _reserve(owner, shape, copies=1, itemsize=8):
    need(all(type(x) is int and x >= 0 for x in shape), "explicit nonnegative array shape")
    owner.reserve("retained_bytes", math.prod(shape) * copies * itemsize)


def _upper_fraction(value):
    """Small exact-rational constants rounded outward, not an epsilon policy."""
    need(type(value) is Fraction and value >= 0, "nonnegative exact bound")
    result = float(value)
    need(math.isfinite(result), "finite exact-rational bound")
    if Fraction.from_float(result) < value:
        result = math.nextafter(result, math.inf)
    need(math.isfinite(result), "finite outward constant")
    return result


def _lower_fraction(value):
    need(type(value) is Fraction and value >= 0, "nonnegative exact lower bound")
    result = float(value)
    need(math.isfinite(result), "finite exact-rational lower bound")
    if Fraction.from_float(result) > value:
        result = math.nextafter(result, -math.inf)
    need(result >= 0, "nonnegative outward lower constant")
    return result


def _gamma(operations):
    need(type(operations) is int and operations > 0, "positive exact operation count")
    product = operations * U
    need(product < 1, "roundoff operation count exceeds valid gamma domain")
    return _upper_fraction(product / (1 - product)), _upper_fraction(operations * ETA / (1 - product))


def _up(value, np):
    result = np.nextafter(value, np.inf)
    need(np.isfinite(result).all() and np.all(result >= 0), "finite nonnegative outward bound")
    return result


def _add(a, b, np):
    return _up(a + b, np)


def _mul(a, b, np):
    return _up(a * b, np)


def _divide(a, b, np):
    need(np.isfinite(b).all() and np.all(b > 0), "strictly positive interval denominator")
    return _up(a / b, np)


def _down_nonnegative(value, np):
    return np.maximum(0.0, np.nextafter(value, -np.inf))


def _sqrt_upper_scalar(value):
    need(type(value) is float and math.isfinite(value) and value >= 0, "finite nonnegative square root bound")
    result = math.sqrt(value)
    # Verify the final scalar enclosure exactly. No libm ulp default is used.
    target = Fraction.from_float(value)
    while Fraction.from_float(result) ** 2 < target:
        result = math.nextafter(result, math.inf)
        need(math.isfinite(result), "finite square root enclosure")
    return result


def _sqrt_lower_scalar(value):
    need(type(value) is float and math.isfinite(value) and value >= 0, "finite nonnegative square root lower bound")
    result = math.sqrt(value)
    target = Fraction.from_float(value)
    while Fraction.from_float(result) ** 2 > target:
        result = math.nextafter(result, -math.inf)
        need(result >= 0, "nonnegative square root enclosure")
    return result


def _positive_sum_upper(values):
    """Explicit ordered scalar additions, each rounded outward.

    This deliberately avoids assuming an undocumented reduction tree for an
    enclosure. Cost is included in this fit's CPU/wall observation.
    """
    total = 0.0
    for value in values.flat:
        number = float(value)
        need(math.isfinite(number) and number >= 0, "finite nonnegative bound summand")
        total = math.nextafter(total + number, math.inf)
        need(math.isfinite(total), "finite bound sum")
    return total


def _frob_upper(values, np):
    need(np.isfinite(values).all(), "finite norm operand")
    maximum = float(np.max(np.abs(values), initial=0.0))
    if maximum == 0.0:
        return 0.0
    # A scaled enclosure avoids squaring large finite matrix entries directly.
    scaled = _divide(np.abs(values), maximum, np)
    squared = _mul(scaled, scaled, np)
    root = _sqrt_upper_scalar(_positive_sum_upper(squared))
    return _upper_fraction(Fraction.from_float(maximum) * Fraction.from_float(root))


def _rounding_error(computed, np):
    """Bound one final binary64 operation from its rounded result."""
    factor = _upper_fraction(U / (1 - U))
    tiny = _upper_fraction(ETA / (1 - U))
    return _add(_mul(np.abs(computed), factor, np), tiny, np)


def _matmul(left, right, owner, np):
    """Computed dot products and entrywise formation enclosure.

    A k-term product uses a conservative2k elementary-operation count. The
    computed absolute-product sum is itself inflated by its own forward bound,
    so it is not mistaken for the exact sum of absolute products. This is
    conditional on a verified native arithmetic DAG with at most2k rounded
    scalar operations per dot, or a proved FMA-equivalent bound. Library name
    and version alone do not establish that implementation property.
    """
    need(left.ndim == right.ndim == 2 and left.shape[1] == right.shape[0] and left.shape[1] > 0,
         "nonempty compatible complete matrix product")
    rows, terms, columns = int(left.shape[0]), int(left.shape[1]), int(right.shape[1])
    _reserve(owner, (rows, columns), copies=8)
    _reserve(owner, tuple(map(int, left.shape)))
    _reserve(owner, tuple(map(int, right.shape)))
    result = left @ right
    absolute = np.abs(left) @ np.abs(right)
    need(np.isfinite(result).all() and np.isfinite(absolute).all() and np.all(absolute >= 0),
         "finite full binary64 dot product; overflow refuses")
    gamma, underflow = _gamma(2 * terms)
    need(gamma < 1.0, "finite absolute-dot inflation domain")
    denominator = _upper_fraction(1 / (1 - Fraction.from_float(gamma)))
    # gamma above is rounded up. Its use in 1/(1-gamma) is conservative.
    absolute_upper = _mul(_add(absolute, underflow, np), denominator, np)
    error = _add(_mul(absolute_upper, gamma, np), underflow, np)
    return result, error


def _accumulate(total, bound, value, error, np):
    updated = total + value
    need(np.isfinite(updated).all(), "finite ordered Gram accumulation")
    updated_bound = _add(_add(bound, error, np), _rounding_error(updated, np), np)
    return updated, updated_bound


def _mean_error(values, mean, owner, np):
    """Conditional enclosure for NumPy's full-axis mean of binary64 inputs.

    The qualified reduction must use at most n additions per column and one
    division, without reduced precision. The conservative2n+2 count covers
    those operations; it does not purport to qualify an unknown native build.
    """
    n = int(values.shape[0])
    _reserve(owner, (1, n))
    absolute_sum, absolute_error = _matmul(np.ones((1, n), dtype=np.float64), np.abs(values), owner, np)
    absolute_upper = _add(absolute_sum[0], absolute_error[0], np)
    gamma, underflow = _gamma(2 * n + 2)
    return _add(_divide(_mul(absolute_upper, gamma, np), float(n), np), underflow, np)


def _state_identity(mean, scale, constant, second, np):
    from .models import array_identity
    return {name: array_identity(np.ascontiguousarray(value)) for name, value in
            (("mean", mean), ("scale", scale), ("constant", constant), ("pca_mean", second))}


def _standardize(values, train_positions, owner, np):
    """Exact selected operation order plus preprocessing error envelopes.

    Returns the computed complete centered block, its entrywise envelope against
    exact-real scaling of the same binary64 input values, and compact stats.
    Constant columns are known from exact equality and deliberately become0.
    """
    rows, width = map(int, values.shape)
    _reserve(owner, (rows, width), copies=18)
    _reserve(owner, (len(train_positions), width), copies=12)
    _reserve(owner, (width,), copies=24)
    raw = np.array(values, dtype=np.float64, order="C", copy=True)
    need(np.isfinite(raw).all(), "finite full feature block")
    training = np.ascontiguousarray(raw[train_positions])
    mean = training.mean(axis=0)
    constant = np.all(training == training[0], axis=0)
    centered_training = training - mean
    variance = np.mean(centered_training ** 2, axis=0)
    scale = np.sqrt(variance)
    need(np.isfinite(mean).all() and np.isfinite(scale).all() and np.all(scale[~constant] > 0),
         "finite nonconstant full feature scale")
    scale[constant] = 1.0
    centered_raw = raw - mean
    standardized = centered_raw / scale
    standardized[:, constant] = 0.0
    second = standardized[train_positions].mean(axis=0)
    output = standardized - second
    need(np.isfinite(output).all(), "finite full PCA second-centered feature block")

    mean_error = _mean_error(training, mean, owner, np)
    center_error = _add(_rounding_error(centered_training, np), mean_error, np)
    square = centered_training ** 2
    square_error = _add(_rounding_error(square, np),
                       _add(_mul(_mul(2.0, np.abs(centered_training), np), center_error, np),
                            _mul(center_error, center_error, np), np), np)
    variance_error = _add(_mean_error(square, variance, owner, np),
                          _mean_nonnegative_upper(square_error, owner, np), np)
    lower_variance = _down_nonnegative(variance - variance_error, np)
    need(np.all(lower_variance[~constant] > 0),
         "nonconstant feature variance is numerically unresolved; no arbitrary scale floor")
    # sqrt is enclosed elementwise by nextafter and checked finite. Correctly
    # rounded binary64 sqrt belongs to the stated native arithmetic assumptions.
    lower_root = np.maximum(0.0, np.nextafter(np.sqrt(lower_variance), -np.inf))
    scale_round = _rounding_error(scale, np)
    denom = np.nextafter(lower_root + np.maximum(np.nextafter(scale, -np.inf), 0.0), -np.inf)
    denom[constant] = 1.0
    scale_error = _add(_divide(variance_error, denom, np), scale_round, np)
    scale_error[constant] = 0.0
    scale_lower = np.nextafter(scale - scale_error, -np.inf)
    scale_lower[constant] = 1.0
    need(np.all(scale_lower > 0), "feature scale inverse is unresolved under propagated roundoff")
    numerator_error = _add(_rounding_error(centered_raw, np), mean_error, np)
    division_round = _rounding_error(standardized, np)
    z_error = _add(division_round,
                  _add(_divide(numerator_error, scale_lower, np),
                       _divide(_mul(_add(np.abs(standardized), division_round, np), scale_error, np),
                               scale_lower, np), np), np)
    z_error[:, constant] = 0.0
    second_error = _add(_mean_error(standardized[train_positions], second, owner, np),
                        _mean_nonnegative_upper(z_error[train_positions], owner, np), np)
    output_error = _add(_rounding_error(output, np), _add(z_error, second_error, np), np)
    output[:, constant] = 0.0
    output_error[:, constant] = 0.0
    return output, output_error, (mean, scale, constant, second), _state_identity(mean, scale, constant, second, np)


def _mean_nonnegative_upper(values, owner, np):
    n = int(values.shape[0])
    _reserve(owner, (1, n))
    summed, error = _matmul(np.ones((1, n), dtype=np.float64), values, owner, np)
    return _divide(_add(summed[0], error[0], np), float(n), np)


def _apply(values, stats, stats_error, owner, np):
    """Apply unchanged chronological TRAIN state to a reversed feature block."""
    mean, scale, constant, second = stats
    _reserve(owner, tuple(map(int, values.shape)), copies=8)
    raw = np.array(values, dtype=np.float64, order="C", copy=True)
    output = (raw - mean) / scale
    output[:, constant] = 0.0
    output -= second
    need(np.isfinite(output).all(), "finite reversed values under chronological TRAIN transform")
    # Exact chronological TRAIN state and its propagated intervals are reused.
    # Reversed magnitudes enter their own arithmetic bound; they are never
    # assumed equal to the chronological input magnitudes.
    mean_error, scale_error, second_error = stats_error
    lower = np.nextafter(scale - scale_error, -np.inf)
    lower[constant] = 1.0
    need(np.all(lower > 0), "positive captured chronological scale enclosure")
    centered = raw - mean
    standardized = centered / scale
    numerator = _add(_rounding_error(centered, np), mean_error, np)
    division = _rounding_error(standardized, np)
    bound = _add(division, _add(_divide(numerator, lower, np),
                 _divide(_mul(_add(np.abs(standardized), division, np), scale_error, np), lower, np), np), np)
    bound = _add(_rounding_error(output, np), _add(bound, second_error, np), np)
    output[:, constant] = 0.0
    bound[:, constant] = 0.0
    return output, bound


def _stats_envelopes(values, train_positions, stats, owner, np):
    """Repeat exact selected stats arithmetic solely to retain compact errors."""
    mean, scale, constant, second = stats
    _reserve(owner, (len(train_positions), int(values.shape[1])), copies=16)
    _reserve(owner, (int(values.shape[1]),), copies=16)
    training = np.asarray(values, dtype=np.float64)[train_positions]
    centered = training - mean
    mean_error = _mean_error(training, mean, owner, np)
    center_error = _add(_rounding_error(centered, np), mean_error, np)
    square = centered ** 2
    variance = square.mean(axis=0)
    square_error = _add(_rounding_error(square, np),
                      _add(_mul(_mul(2.0, np.abs(centered), np), center_error, np),
                           _mul(center_error, center_error, np), np), np)
    variance_error = _add(_mean_error(square, variance, owner, np),
                         _mean_nonnegative_upper(square_error, owner, np), np)
    lower_root = np.maximum(0.0, np.nextafter(np.sqrt(_down_nonnegative(variance - variance_error, np)), -np.inf))
    denom = np.nextafter(lower_root + np.maximum(np.nextafter(scale, -np.inf), 0.0), -np.inf)
    denom[constant] = 1.0
    scale_error = _add(_divide(variance_error, denom, np), _rounding_error(scale, np), np)
    scale_error[constant] = 0.0
    lower = np.nextafter(scale - scale_error, -np.inf)
    lower[constant] = 1.0
    need(np.all(lower > 0), "finite positive TRAIN scale interval")
    standardized = centered / scale
    standardized[:, constant] = 0.0
    division = _rounding_error(standardized, np)
    z_error = _add(division, _add(_divide(center_error, lower, np),
              _divide(_mul(_add(np.abs(standardized), division, np), scale_error, np), lower, np), np), np)
    z_error[:, constant] = 0.0
    second_error = _add(_mean_error(standardized, second, owner, np),
                        _mean_nonnegative_upper(z_error, owner, np), np)
    mean_error[constant] = 0.0
    second_error[constant] = 0.0
    return mean_error, scale_error, second_error


def _preprocessing_effect(left, right, left_error, right_error, np):
    a, b = _frob_upper(left, np), _frob_upper(right, np)
    ea, eb = _frob_upper(left_error, np), _frob_upper(right_error, np)
    value = Fraction.from_float(ea) * Fraction.from_float(b)
    value += Fraction.from_float(a) * Fraction.from_float(eb)
    value += Fraction.from_float(ea) * Fraction.from_float(eb)
    return _upper_fraction(value)


def _spectrum(gram, formation_bound, preprocessing_bound, owner, np):
    n = int(gram.shape[0])
    _reserve(owner, (n, n), copies=18)
    _reserve(owner, (n,), copies=8)
    # Explicit averaging makes the matrix passed to eigh symmetric. Its added
    # error is included relative to the originally accumulated complete Gram.
    sym = (gram + gram.T) / 2.0
    need(np.isfinite(sym).all(), "finite symmetric full TRAIN Gram")
    symmetry_delta = sym - gram
    symmetry_error = _frob_upper(_add(np.abs(symmetry_delta), _rounding_error(symmetry_delta, np), np), np)
    eigenvalues, vectors = np.linalg.eigh(sym)
    order = np.arange(n - 1, -1, -1)
    eigenvalues = np.ascontiguousarray(eigenvalues[order])
    vectors = np.ascontiguousarray(vectors[:, order])
    need(np.isfinite(eigenvalues).all() and np.isfinite(vectors).all(), "finite full eigensystem")
    orthogonal, orth_bound = _matmul(vectors.T, vectors, owner, np)
    defect = orthogonal - np.eye(n, dtype=np.float64)
    orth_bound = _add(orth_bound, _rounding_error(defect, np), np)
    eta = _frob_upper(_add(np.abs(defect), orth_bound, np), np)
    need(eta < 1.0, "eigenvector orthogonality is not certifiable")
    scaled = vectors * eigenvalues[None, :]
    scaled_error = _rounding_error(scaled, np)
    reconstructed, reconstruction_bound = _matmul(scaled, vectors.T, owner, np)
    propagated, propagated_error = _matmul(scaled_error, np.abs(vectors.T), owner, np)
    reconstruction_bound = _add(reconstruction_bound, _add(propagated, propagated_error, np), np)
    residual = sym - reconstructed
    reconstruction_bound = _add(reconstruction_bound, _rounding_error(residual, np), np)
    r = _frob_upper(_add(np.abs(residual), reconstruction_bound, np), np)
    # Polar-factor certificate: ||U-Q|| <= eta/(1+sqrt(1-eta)).
    lower_root = _sqrt_lower_scalar(_lower_fraction(1 - Fraction.from_float(eta)))
    lower_denominator = _lower_fraction(1 + Fraction.from_float(lower_root))
    need(lower_denominator > 0, "positive polar denominator")
    d = _upper_fraction(Fraction.from_float(eta) / Fraction.from_float(lower_denominator))
    L = float(np.max(np.abs(eigenvalues)))
    upper_root = _sqrt_upper_scalar(_upper_fraction(1 + Fraction.from_float(eta)))
    polar = Fraction.from_float(d) * Fraction.from_float(L) * (Fraction.from_float(upper_root) + 1)
    form = _frob_upper(formation_bound, np)
    total = Fraction.from_float(form) + Fraction.from_float(preprocessing_bound)
    total += Fraction.from_float(symmetry_error) + Fraction.from_float(r) + polar
    error = _upper_fraction(total)
    need(np.all(eigenvalues >= -error), "negative eigenvalue below certified formation/eigensystem envelope")
    # Unresolved signs/ranks are not treated as resolved positive variance.
    observed = np.maximum(eigenvalues, 0.0)
    denominator = float(observed.sum())
    need(math.isfinite(denominator) and denominator > 0.0, "undefined full PCA variance")
    k = min(n, int(np.searchsorted(np.cumsum(observed) / denominator, 0.95, side="right")) + 1)
    lower = np.maximum(0.0, np.nextafter(eigenvalues - error, -np.inf))
    upper = _up(np.maximum(0.0, eigenvalues + error), np)
    total_lower = sum((Fraction.from_float(float(x)) for x in lower), Fraction())
    total_upper = sum((Fraction.from_float(float(x)) for x in upper), Fraction())
    need(total_lower > 0, "total variance is unresolved under its error interval")
    at_lower = sum((Fraction.from_float(float(x)) for x in lower[:k]), Fraction()) / total_upper
    previous_upper = sum((Fraction.from_float(float(x)) for x in upper[:k-1]), Fraction()) / total_lower
    threshold = Fraction(95, 100)
    need(at_lower > threshold and previous_upper <= threshold,
         "95% right-search cutoff is numerically unresolved; require full SVD comparison")
    need(np.all(eigenvalues[:k] > error), "retained PCA direction has unresolved rank/inverse square root")
    resolved = int(np.count_nonzero(eigenvalues > error))
    need(k == resolved or k == n or Fraction.from_float(float(eigenvalues[k-1])) - Fraction.from_float(float(eigenvalues[k])) > 2 * Fraction.from_float(error),
         "PCA cutoff crosses unresolved eigenvalue tie/cluster; do not change selected rank")
    certificate = {"formation_frobenius_bound": form, "preprocessing_gram_effect_bound": preprocessing_bound,
        "symmetry_effect_bound":symmetry_error, "orthogonality_frobenius_upper":eta,
        "reconstruction_frobenius_upper":r,"polar_basis_distance_upper":d,
        "spectral_error_upper":error,"resolved_positive_directions":resolved,
        "unresolved_directions":n-resolved,"retained_directions":k,
        "retention_rule":"strict cumulative variance >0.95; right-search; certified interval and boundary gap",
        "fraction_at_cutoff_lower":_lower_fraction(at_lower),"fraction_before_cutoff_upper":_upper_fraction(previous_upper),
        "negative_policy":"values below -E refuse; unresolved complement retained in variance interval, never resource-truncated"}
    return eigenvalues, vectors, k, certificate


def _projection(cross, cross_bound, cross_preprocessing, vectors, eigenvalues, owner, np):
    retained = len(eigenvalues)
    _reserve(owner, (int(cross.shape[0]), retained), copies=10)
    raw, error = _matmul(cross, vectors, owner, np)
    propagated, propagated_error = _matmul(cross_bound, np.abs(vectors), owner, np)
    error = _add(error, _add(propagated, propagated_error, np), np)
    # A scalar Frobenius bound is a valid bound for every entry; multiplying by
    # each column's L2 norm bounds propagation to that computed eigenvector.
    norms = np.asarray([_frob_upper(vectors[:,j],np) for j in range(retained)], dtype=np.float64)
    error = _add(error, _mul(cross_preprocessing,norms[None,:],np),np)
    root = np.sqrt(eigenvalues)
    root_error = _rounding_error(root,np)
    lower = np.nextafter(root-root_error,-np.inf)
    need(np.all(lower>0),"positive retained inverse-square-root enclosure")
    scores = raw/root
    division = _rounding_error(scores,np)
    bound = _add(division,_add(_divide(error,lower,np),
             _divide(_mul(_add(np.abs(scores),division,np),root_error,np),lower,np),np),np)
    need(np.isfinite(scores).all() and np.isfinite(bound).all(),"finite full projected score/error envelope")
    return np.ascontiguousarray(scores),np.ascontiguousarray(bound)


