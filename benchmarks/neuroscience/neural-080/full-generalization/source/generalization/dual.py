    expected={"schema","backend","block","input_width","output_width","train_video_ids","video_ids",
              "scores","reversed_scores","eigenvalues","eigenvectors","certificate","column_states",
              "stream_spec_sha256","qualification"}
    need(type(document) is dict and set(document)==expected and document["schema"]=="neural080_streamed_pca_state_v1" and
         document["backend"]==BACKEND and document["block"] in LEARNED and document["input_width"]==INPUT_WIDTH,
         "closed selected streamed PCA state")
