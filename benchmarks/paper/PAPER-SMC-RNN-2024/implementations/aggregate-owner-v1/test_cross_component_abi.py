"""Real episode/journal/scope interfaces over generated memory-backed boundaries.

No fixture writes or native lifecycle; no image, cgroup or fsync qualification.
Source and selection validators run against synthetic in-memory selection bytes.
"""
import copy
from contextlib import ExitStack
import importlib.util
from pathlib import Path
import stat
import sys
from types import SimpleNamespace
import unittest
from unittest.mock import patch

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import cgroup
import common
import journal

EPISODE_PATH = HERE.parent / 'aggregate-episode-v1' / 'episode.py'
SPEC = importlib.util.spec_from_file_location('_smc_cross_component_episode', EPISODE_PATH)
episode = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(episode)
SOURCE_BYTES = {name: (episode.HERE / name).read_bytes() for name in (
    'SOURCE.json', 'episode.py', 'worker.py', 'MATERIAL_BINDING.json')}
encoded, pin = common.encoded, common.pin
BOOT = '12345678-1234-1234-1234-123456789abc'
ROOT = Path('/generated/smc-owner')
OUTPUT = Path('/generated/smc-output')
OWNER_SOURCE = pin(b'generated-unqualified-owner-source')


class MemoryFiles:
    def __init__(self):
        self.files, self.trace = {}, []
        self.corrupt_intent = None

    def put(self, path, value):
        raw = encoded(value)
        self.files[str(path)] = raw
        return pin(raw)

    def body(self, path, expected=None, cap=common.FRAME_CAP):
        raw = self.files[str(path)]
        common.need(len(raw) <= cap, 'generated byte cap')
        if expected is not None:
            common.need(pin(raw) == common.descriptor(expected), 'generated pinned byte read')
        return raw

    def read(self, path, expected=None):
        # Actual pin and duplicate-key validators parse generated bytes.
        raw = self.body(path)
        if expected is not None:
            cgroup.need(pin(raw) == cgroup.descriptor(expected), 'exact generated metadata pin')
        return cgroup.decoded(raw)

    def publish(self, path, value, **_):
        saved = copy.deepcopy(value)
        if saved.get('message', {}).get('event') == 'CGROUP-INTENT' and self.corrupt_intent:
            self.corrupt_intent(saved)
        result = self.put(path, saved)
        self.trace.append(('publish', str(path), saved))
        return result


def selected():
    return {'image': 'sha256:' + 'b' * 64,
        'docker_binary': '/generated/bin/docker', 'docker_socket': '/generated/run/docker.sock',
        'boot_id': BOOT, 'pid_limit': 32,
        'qualification': {'path': '/generated/qualification.json', **pin(b'not-runtime-proof')},
        'resource_policy': 'measured_caps_and_oom_kill_v1', 'cgroup_driver': 'cgroupfs',
        'delegation': {'path': '/sys/fs/cgroup/generated-smc', 'st_dev': 55,
            'st_ino': 99, 'uid': 1000, 'mount_id': 71, 'mount_point': '/sys/fs/cgroup',
            'mount_root': '/', 'fs_type': 'cgroup2'}}


class Harness:
    """Memory-backed external boundaries; validators and lifecycle methods real."""
    def __init__(self, mutate=None):
        self.files, self.stack = MemoryFiles(), ExitStack()
        self.selection = selected()
        if mutate:
            mutate(self.selection)
        binding = {'schema': 'smc_aggregate_deployment_binding_v1', 'state': 'selected',
                   'selected': self.selection, 'missing': []}
        for name, raw in SOURCE_BYTES.items():
            self.files.files[str(episode.HERE / name)] = raw
        self.files.put(episode.HERE / 'DEPLOYMENT_BINDING.json', binding)
        manifest = episode.decode(SOURCE_BYTES['SOURCE.json'])
        manifest['active_deployment_binding'] = 'selected'
        manifest['files']['DEPLOYMENT_BINDING.json'] = pin(
            self.files.body(episode.HERE / 'DEPLOYMENT_BINDING.json'))
        self.files.put(episode.HERE / 'SOURCE.json', manifest)
        self.clock = {'origin': 1.0, 'controller_deadline': 1000.0, 'deadline': 1060.0,
                      'outcome': 'improvement', 'clock_identity': 'linux:' + BOOT}
        self.fd_paths, self.created, self.settings = {}, {}, {}
        self.next_fd = 100
        self.host_reads = []

    def __enter__(self):
        patches = [
            patch.object(episode, 'body', lambda path, cap=episode.META_CAP: self.files.body(path, cap=cap)),
            patch.object(Path, 'is_symlink', lambda _: False),
            patch.object(cgroup, '_file', self.files.read),
            patch.object(cgroup, 'directory', self.directory),
            patch.object(cgroup, '_read_kernel', self.read_kernel),
            patch.object(cgroup, '_write_kernel', self.write_kernel),
            patch.object(cgroup, '_identity', self.identity),
            patch.object(cgroup, '_magic', self.magic),
            patch.object(cgroup.os, 'open', self.open_scope),
            patch.object(cgroup.os, 'close', lambda fd: self.files.trace.append(('close-fd', fd))),
            patch.object(cgroup.os, 'mkdir', self.mkdir),
            patch.object(cgroup.os, 'stat', self.stat_scope),
            patch.object(cgroup.os, 'fchmod', self.chmod),
            patch.object(cgroup.os, 'getpid', lambda: 901),
            patch.object(cgroup.os, 'geteuid', lambda: 1000),
            patch.object(cgroup.sys, 'platform', 'linux'),
            patch.object(cgroup.time, 'monotonic', lambda: 10.0),
            patch.object(journal, 'body', self.files.body),
        ]
        for item in patches:
            self.stack.enter_context(item)
        return self

    def __exit__(self, *_):
        self.stack.close()

    def directory(self, path):
        path = str(path)
        allowed = {str(ROOT), '/proc/sys/kernel/random', '/proc/901', self.selection['delegation']['path']}
        assert path in allowed, ('unexpected directory boundary', path)
        self.next_fd += 1
        self.fd_paths[self.next_fd] = path
        return self.next_fd

    def magic(self, fd):
        return cgroup.PROC_MAGIC if self.fd_paths[fd].startswith('/proc/') else cgroup.CGROUP_MAGIC

    def identity(self, fd):
        path = self.fd_paths[fd]
        if path == self.selection['delegation']['path']:
            return {k: self.selection['delegation'][k] for k in ('st_dev', 'st_ino', 'uid')}
        return self.created[Path(path).name]['identity'].copy()

    def read_kernel(self, fd, name, cap=cgroup.MAX_INTERFACE):
        path = self.fd_paths[fd]
        self.host_reads.append((path, name))
        if path == '/proc/sys/kernel/random':
            assert name == 'boot_id'
            return BOOT + '\n'
        if path == '/proc/901':
            if name == 'mountinfo':
                return '71 70 0:55 / /sys/fs/cgroup rw - cgroup2 cgroup rw\n'
            assert name == 'cgroup'
            return '0::/controller-outside-delegation\n'
        values = {'cgroup.controllers': 'cpu memory pids\n', 'cgroup.subtree_control': 'cpu memory pids\n',
            'cgroup.type': 'domain\n', 'cgroup.procs': '', 'cgroup.events': 'populated 0\nfrozen 0\n',
            'cpu.stat': 'usage_usec 0\nuser_usec 0\nsystem_usec 0\n',
            'memory.events': 'low 0\nhigh 0\nmax 0\noom 0\noom_kill 0\noom_group_kill 0\n',
            'pids.events': 'max 0\n', 'memory.peak': '0\n'}
        result = self.settings.get((path, name), values.get(name))
        assert result is not None and len(result) <= cap, ('unexpected kernel read', path, name)
        return result

    def write_kernel(self, fd, name, value):
        assert name in {'cgroup.subtree_control', 'memory.max', 'memory.swap.max', 'pids.max', 'cpu.max'}
        path = self.fd_paths[fd]
        assert Path(path).name in self.created
        self.files.trace.append(('kernel-write', path, name, value))
        self.settings[path, name] = ('cpu memory pids' if name == 'cgroup.subtree_control' else value) + '\n'

    def mkdir(self, name, mode, dir_fd):
        assert self.fd_paths[dir_fd] == self.selection['delegation']['path'] and mode == 0o700
        assert name not in self.created
        self.files.trace.append(('mkdir', name))
        self.created[name] = {'identity': {'st_dev': 55, 'st_ino': 2000 + len(self.created), 'uid': 1000},
                              'mode': stat.S_IFDIR | mode}

    def open_scope(self, name, flags, *, dir_fd):
        assert name in self.created and self.fd_paths[dir_fd] == self.selection['delegation']['path']
        assert flags == cgroup.os.O_RDONLY | cgroup.os.O_DIRECTORY | cgroup.os.O_NOFOLLOW | cgroup.os.O_CLOEXEC
        self.next_fd += 1
        self.fd_paths[self.next_fd] = self.fd_paths[dir_fd] + '/' + name
        return self.next_fd

    def chmod(self, fd, mode):
        assert mode == 0o700 and Path(self.fd_paths[fd]).name in self.created

    def stat_scope(self, name, *, dir_fd, follow_symlinks):
        assert follow_symlinks is False and self.fd_paths[dir_fd] == self.selection['delegation']['path']
        item = self.created[name]
        return SimpleNamespace(st_mode=item['mode'], st_dev=item['identity']['st_dev'],
                               st_ino=item['identity']['st_ino'], st_uid=item['identity']['uid'])

    def construct(self):
        self.deployment = episode.deployment_binding()
        self.invocation = {'output': str(OUTPUT), 'owner': str(ROOT),
            'protocol_path': '/generated/protocol/PROTOCOL.json', 'protocol_pin': pin(b'generated-protocol'),
            'source': OWNER_SOURCE, 'aggregate_nonce': 'a' * 32,
            'deployment_pin': self.deployment['binding_pin'], 'clock': copy.deepcopy(self.clock)}
        self.invocation_pin = self.files.put(ROOT / 'INVOCATION.json', self.invocation)
        self.scopes = cgroup.ScopeManager(self.deployment, self.clock, self.invocation_pin,
                                          OWNER_SOURCE, self.files, ROOT)
        self.runtime = {'image': self.deployment['image'], 'deployment': self.deployment,
                        'source_read_bytes': 2**26, 'host_write_bytes': 2**26}
        self.protocol = {'source': episode.source_identity(), 'outcome': 'improvement'}
        self.legacy = SimpleNamespace(**{name: getattr(episode, name) for name in (
            'REQUEST_SCHEMA', 'JOURNAL_SCHEMA', 'OWNERSHIP_SCHEMA', 'TRANSPORT_SHA',
            'COMMAND', 'resources', 'aggregate_plan', 'read')},
            admit_protocol=lambda *_: (self.protocol, self.runtime))
        self.parent = journal.ParentJournal(ROOT / 'events', self.invocation, self.invocation_pin,
            OWNER_SOURCE, self.legacy, SimpleNamespace(), self.files, self.scopes)
        return self.scopes

    def call(self, name, value, **kwargs):
        message = {'schema': 'smc_owner_rpc_v1', 'invocation_pin': self.invocation_pin,
                   'sequence': self.parent.sequence, 'event': name, 'value': value}
        ack = self.parent.accept(message, **kwargs)
        assert ack == {'schema': 'smc_owner_ack_v1', 'sequence': message['sequence'],
                       'message_pin': pin(encoded(message))}
        self.files.trace.append(('ack', name))
        return ack

    def prepare_pair(self):
        self.call('CONTROLLER-READY', {'generated_birth': True}, controller_check=lambda _: None)
        for phase in episode.CONDITIONS:
            exposure = self.files.put(OUTPUT / 'jobs' / phase / 'EXPOSURE.json', {'phase': phase})
            request = {'schema': episode.REQUEST_SCHEMA, 'phase_id': phase, 'action': 'held_attempt',
                'role': 'A' if phase == episode.CONDITIONS[0] else 'B', 'image': self.runtime['image'],
                'command': episode.COMMAND, 'workdir': '/work', 'source': self.protocol['source'],
                'exposure': exposure, 'clock': {'origin': self.clock['origin'],
                                               'phase_deadline': self.clock['controller_deadline']},
                'resources': episode.resources('improvement', self.runtime),
                'aggregate': episode.aggregate_plan(self.invocation, self.invocation_pin, phase, self.runtime),
                'output': {'kind': 'generic', 'manifest': 'OUTPUTS.json'}}
            request_pin = self.files.put(OUTPUT / 'jobs' / phase / 'REQUEST.json', request)
            self.call('PREPARED', {'request': request, 'request_file': request_pin})

    def provider(self, name, value, phase):
        row = {'schema': episode.JOURNAL_SCHEMA, 'phase_id': phase,
            'request_sha256': pin(encoded(self.parent.prepared[phase]))['sha256'],
            'index': self.parent.indices[phase], 'event': name, 'value': value}
        return self.call(name, {'record': row, 'pin': pin(encoded(row))})

    def own(self, phase):
        request = self.parent.prepared[phase]
        prefix = 'osl-' + ('a' if phase == episode.CONDITIONS[0] else 'b') * 24
        ownership = {'schema': episode.OWNERSHIP_SCHEMA, 'phase_id': phase,
            'request_pin': pin(encoded(request)), 'engine_source_pin': {'bytes': 1, 'sha256': episode.TRANSPORT_SHA},
            'original_deadline': self.clock['deadline'], 'phase_deadline': self.clock['controller_deadline'],
            'attempt_prefix': prefix, 'aggregate': request['aggregate'],
            'resources': {key: {'kind': 'volume' if key == 'volume' else 'container',
                'name': prefix + '-' + key, 'owner': prefix + '/' + key,
                'attempted': False, 'acknowledged': False} for key in ('volume', 'holder', 'producer')}}
        self.provider('OWNERSHIP', {'ownership': ownership, 'ownership_pin': pin(encoded(ownership))}, phase)

    def intent(self, phase):
        request = self.parent.prepared[phase]
        return self.provider('CGROUP-INTENT', {'plan': request['aggregate'], 'limits': request['resources']}, phase)


class CrossComponentABI(unittest.TestCase):
    def test_selected_raw_uuid_reaches_real_scope_host_validation(self):
        with Harness() as h:
            scopes = h.construct()
            self.assertEqual(scopes.deployment, h.deployment)
            self.assertEqual(scopes.clock, h.clock)
            self.assertEqual(scopes.clock['clock_identity'], 'linux:' + h.deployment['boot_id'])
            self.assertIn(('/proc/sys/kernel/random', 'boot_id'), h.host_reads)
            self.assertIn(('/proc/901', 'mountinfo'), h.host_reads)
            self.assertEqual(scopes.scopes, {})

    def test_prefixed_boot_uuid_is_refused_by_actual_episode_selection(self):
        with Harness(lambda row: row.update(boot_id='linux:' + BOOT)) as h:
            with self.assertRaisesRegex(ValueError, 'same-boot Linux deployment'):
                h.construct()
            self.assertEqual(h.host_reads, [])
            self.assertEqual(h.created, {})

    def test_narrow_scope_binding_refusals_are_explicit(self):
        # Selection shape is broader than executable scope support. These are
        # intentional fail-closed differences, not interchangeable deployments.
        cases = {
            'PID1': lambda row: row.update(pid_limit=1),
            'alternate_mount': lambda row: row['delegation'].update(
                path='/generated/cgroup/delegated', mount_point='/generated/cgroup'),
            'zero_inode': lambda row: row['delegation'].update(st_ino=0),
            'zero_mount_id': lambda row: row['delegation'].update(mount_id=0),
        }
        for label, mutation in cases.items():
            with self.subTest(label=label), Harness(mutation) as h:
                self.assertEqual(episode.deployment_binding()['boot_id'], BOOT)
                with self.assertRaisesRegex(ValueError, 'exact delegated cgroup2 host binding'):
                    h.construct()
                self.assertEqual(h.host_reads, [])
                self.assertEqual(h.created, {})

    def test_both_parent_intents_prepare_full_resources_and_original_receipt_paths(self):
        with Harness() as h:
            scopes = h.construct()
            h.prepare_pair()
            for phase in episode.CONDITIONS:
                h.own(phase)
                start = len(h.files.trace)
                h.intent(phase)
                request, scope = h.parent.prepared[phase], scopes.scopes[phase]
                owner_path = ROOT / ('CGROUP-' + phase + '-OWNER.json')
                owner = h.files.read(owner_path, scope['owner_pin'])
                self.assertEqual(len(request['resources']), 19)
                self.assertEqual(set(request['resources']), cgroup.RESOURCE_KEYS)
                for value in (scope, owner, scopes._receipt(phase, scope, scope['last'], [])):
                    self.assertEqual(value['limits'], request['resources'])
                    self.assertEqual(value['request_pin'], pin(encoded(request)))
                self.assertEqual(owner['clock'], h.invocation['clock'])
                self.assertEqual(owner['source'], OWNER_SOURCE)
                self.assertEqual(owner['invocation_pin'], h.invocation_pin)
                intent_ref = owner['intent_ref']
                self.assertEqual(Path(intent_ref['path']).parent, ROOT / 'events')
                intent = h.files.read(intent_ref['path'], {k: intent_ref[k] for k in ('bytes', 'sha256')})
                self.assertEqual(intent['message']['value']['record']['value'],
                                 {'plan': request['aggregate'], 'limits': request['resources']})
                trace = h.files.trace[start:]
                intent_i = next(i for i, item in enumerate(trace) if item[0] == 'publish' and item[1] == intent_ref['path'])
                mkdir_i = next(i for i, item in enumerate(trace) if item[0] == 'mkdir')
                owner_i = next(i for i, item in enumerate(trace) if item[0] == 'publish' and item[1] == str(owner_path))
                ack_i = next(i for i, item in enumerate(trace) if item == ('ack', 'CGROUP-INTENT'))
                self.assertLess(intent_i, mkdir_i)
                self.assertLess(mkdir_i, owner_i)
                self.assertLess(owner_i, ack_i)
                for name, expected in {'memory.max': '8589934592\n', 'memory.swap.max': '0\n',
                    'pids.max': '32\n', 'cpu.max': '600000 100000\n'}.items():
                    self.assertEqual(h.settings[request['aggregate']['path'], name], expected)
            self.assertEqual(h.parent.aggregate_started, set(episode.CONDITIONS))

    def test_real_prepare_rejects_clipped_extra_or_bool_resource_contract(self):
        mutations = [lambda value: value.pop('source_read_bytes'),
                     lambda value: value.update(unrecognized=1),
                     lambda value: value.update(max_files=True)]
        for mutation in mutations:
            with self.subTest(mutation=mutation), Harness() as h:
                scopes = h.construct()
                h.prepare_pair()
                request = h.parent.prepared[episode.CONDITIONS[0]]
                limits = copy.deepcopy(request['resources'])
                mutation(limits)
                with self.assertRaisesRegex(ValueError, 'complete positive-integer transport resource'):
                    scopes.prepare(episode.CONDITIONS[0], request['aggregate'], limits,
                        intent_ref={'path': str(ROOT / 'events/EVENT-000099.json'), **pin(b'not-read')},
                        request_pin=pin(encoded(request)))
                self.assertEqual(h.created, {})
                self.assertEqual(scopes.scopes, {})

    def test_durable_intent_source_invocation_or_request_corruption_precedes_mkdir(self):
        def change_request(wrapped):
            wrapper = wrapped['message']['value']
            wrapper['record']['request_sha256'] = 'f' * 64
            wrapper['pin'] = pin(encoded(wrapper['record']))
        mutations = [lambda value: value.update(owner_source=pin(b'other-source')),
                     lambda value: value.update(invocation_pin=pin(b'other-invocation')), change_request]
        for mutation in mutations:
            with self.subTest(mutation=mutation), Harness() as h:
                h.construct()
                h.prepare_pair()
                phase = episode.CONDITIONS[0]
                h.own(phase)
                h.files.corrupt_intent = mutation
                with self.assertRaises(ValueError):
                    h.intent(phase)
                self.assertEqual(h.created, {})
                self.assertNotIn(phase, h.parent.aggregate_started)
                self.assertNotIn(('ack', 'CGROUP-INTENT'), h.files.trace)


