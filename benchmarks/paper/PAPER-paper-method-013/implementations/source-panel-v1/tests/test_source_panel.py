class GeneratedPanelTests(unittest.TestCase):
    """Fake byte pins exercise the real MAT parser, converter and full-panel scorer.

    The production source pin function is patched only in these generated tests;
    no generated bytes can satisfy the production author's Git blob identities.
    """

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.source = self.root / "invented-source"
        self.source.mkdir()
        self.pins = {}
        for index, rid in enumerate(PANEL.RECORDINGS):
            seg = np.zeros((488, 488, 1), dtype=np.uint8)
            seg[10 + index, 20, 0] = 1
            path = self.source / f"{rid}.mat"
            savemat(path, {"seg": seg}, do_compression=True)
            body = path.read_bytes()
            self.pins[rid] = {"path": path.name, "bytes": len(body),
                              "git_blob_sha1": PANEL.git_blob_sha1(body),
                              "sha256": hashlib.sha256(body).hexdigest()}
        self.patcher = patch.object(PANEL, "source_pins", return_value=self.pins)
        self.patcher.start()
        self.addCleanup(self.patcher.stop)
        self.output = self.root / "reference"

    def convert(self):
        return PANEL.convert_panel(self.source, self.output)

    def prediction(self, reference, *, failed_last=False):
        directory = self.root / "prediction"
        directory.mkdir()
        rows = []
        for index, row in enumerate(reference["recordings"]):
            masks = np.load(self.output / row["mask_file"], allow_pickle=False)
            if failed_last and index == 9:
                masks = np.empty((0, 488, 488), dtype=bool)
            name = row["mask_file"]
            np.save(directory / name, masks, allow_pickle=False)
            rows.append({"recording_id": row["recording_id"], "depth_um": row["depth_um"],
                         "mask_file": name, "mask_sha256": PANEL.sha256(directory / name)})
        manifest = {**PANEL._common(PANEL.PREDICTION_SCHEMA), "recordings": rows,
                    "policy_id": PANEL.POLICY_ID, "method_id": "invented-software-control",
                    "implementation_identity": "invented deterministic masks; no model",
                    "reference_manifest_sha256": PANEL.sha256(self.output / "reference.json")}
        path = directory / "prediction.json"
        path.write_text(json.dumps(manifest))
        return path, manifest

    def test_conversion_all_ten_sources_and_single_method_segmentation(self):
        reference = self.convert()
        self.assertEqual(len(reference["recordings"]), 10)
        self.assertFalse(reference["movie_identity_verified"])
        path, manifest = self.prediction(reference, failed_last=True)
        self.assertNotIn("candidate", manifest)
        self.assertNotIn("traces", manifest)
        self.assertNotIn("runtime", manifest)
        result = PANEL.score_panel(self.output / "reference.json", path, self.source)
        self.assertEqual(result["summary"]["f1"]["macro_video_mean"], 0.9)
        self.assertAlmostEqual(result["summary"]["f1"]["population_sd_ddof0"], 0.3)
        self.assertAlmostEqual(result["summary"]["f1"]["sample_sd_ddof1"], 0.1 ** 0.5)
        self.assertEqual(result["qualification"], "metric_calculation_only")

    def test_changed_source_is_refused_before_output_creation(self):
        pin = next(iter(self.pins.values()))
        path = self.source / pin["path"]
        body = path.read_bytes()
        path.write_bytes(b"X" + body[1:])
        with self.assertRaisesRegex(ValueError, "Git blob mismatch"):
            self.convert()
        self.assertFalse(self.output.exists())

    def test_missing_source_is_refused_before_output_creation(self):
        pin = next(iter(self.pins.values()))
        (self.source / pin["path"]).unlink()
        with self.assertRaisesRegex(ValueError, "source MAT missing"):
            self.convert()
        self.assertFalse(self.output.exists())

    def test_converter_does_not_overwrite_existing_output(self):
        self.output.mkdir()
        marker = self.output / "existing"
        marker.write_text("preserve")
        with self.assertRaisesRegex(ValueError, "already exists"):
            self.convert()
        self.assertEqual(marker.read_text(), "preserve")

    def test_duplicate_or_missing_prediction_video_is_refused(self):
        reference = self.convert()
        path, manifest = self.prediction(reference)
        for rows in (manifest["recordings"][:-1],
                     manifest["recordings"][:-1] + [manifest["recordings"][0]]):
            changed = {**manifest, "recordings": rows}
            path.write_text(json.dumps(changed))
            with self.assertRaises(ValueError):
                PANEL.score_panel(self.output / "reference.json", path, self.source)

    def test_changed_cache_cannot_be_authenticated_with_self_declared_hash(self):
        reference = self.convert()
        first = reference["recordings"][0]
        path = self.output / first["mask_file"]
        masks = np.load(path, allow_pickle=False)
        masks[:] = False
        masks[0, 100, 100] = True
        np.save(path, masks, allow_pickle=False)
        first["mask_sha256"] = PANEL.sha256(path)
        (self.output / "reference.json").write_text(json.dumps(reference))
        prediction, _ = self.prediction(reference)
        with self.assertRaisesRegex(ValueError, "converted masks differ from source"):
            PANEL.score_panel(self.output / "reference.json", prediction, self.source)

    def test_prediction_for_different_reference_is_refused(self):
        reference = self.convert()
        path, manifest = self.prediction(reference)
        manifest["reference_manifest_sha256"] = "0" * 64
        path.write_text(json.dumps(manifest))
        with self.assertRaisesRegex(ValueError, "another reference"):
            PANEL.score_panel(self.output / "reference.json", path, self.source)

    def test_changed_source_after_conversion_is_refused(self):
        reference = self.convert()
        path, manifest = self.prediction(reference)
        first = self.source / next(iter(self.pins.values()))["path"]
        first.write_bytes(b"X" + first.read_bytes()[1:])
        with self.assertRaisesRegex(ValueError, "Git blob mismatch"):
            PANEL.score_panel(self.output / "reference.json", path, self.source)


