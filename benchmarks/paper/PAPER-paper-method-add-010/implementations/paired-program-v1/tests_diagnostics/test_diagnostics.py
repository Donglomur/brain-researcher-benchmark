def need(ok, message):
    if not ok:
        raise AssertionError(message)


def pin(raw):
    return {"bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}


def encoded(value):
    return (json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False) + "\n").encode()


class IO:
    """Bound only this generated fixture's named reads and publications."""
    def __init__(self, root):
        self.root, self.read_bytes, self.write_bytes = root, 0, 0

    def read(self, path, expected=None, cap=262144):
        path = Path(path)
        need(path.is_absolute() and path.resolve() == path, "Canonical source/generated path")
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
        try:
            before = os.fstat(fd)
            need(stat.S_ISREG(before.st_mode) and before.st_nlink == 1 and before.st_size <= cap,
                 "Bounded ordinary source/generated file")
            need(self.read_bytes + before.st_size + 1 <= 4194304, "Generated named-read reservation")
            raw = os.read(fd, before.st_size + 1)
            self.read_bytes += len(raw)
            stamp = lambda s: (s.st_dev, s.st_ino, s.st_mode, s.st_nlink, s.st_size, s.st_mtime_ns, s.st_ctime_ns)
            need(len(raw) == before.st_size and stamp(before) == stamp(os.fstat(fd)) == stamp(path.lstat()),
                 "Stable complete source/generated bytes")
            if expected is not None:
                need(pin(raw) == expected, "Exact selected bytes")
            return raw
        finally:
            os.close(fd)

    def publish(self, path, raw, mode=0o600, cap=65536):
        need(type(raw) is bytes and len(raw) <= cap and self.write_bytes + len(raw) <= 65536,
             "Prospective generated fixture publication bound")
        self.write_bytes += len(raw)
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, mode)
        with os.fdopen(fd, "wb") as stream:
            stream.write(raw); stream.flush(); os.fchmod(stream.fileno(), mode); os.fsync(stream.fileno())
        return pin(raw)

    def write(self, name, value, cap=16384):
        return self.publish(self.root / name, encoded(value), cap=cap)


def load_source(path, name):
    path = Path(path)
    io = IO(path.parent)
    raw = io.read(path)
    module = types.ModuleType(name)
    module.__file__ = str(path)
    sys.modules[name] = module
    exec(compile(raw, str(path), "exec"), module.__dict__)
    return module


