def prepare_inputs(root, kind, transport, io):
    program, data = root / "programme", root / "input"
    program.mkdir(mode=0o700); data.mkdir(mode=0o700)
    wrapper = io.read(PAIRED / "candidate_wrapper.py", transport.WRAPPER_PIN)
    files = {"candidate_wrapper.py": io.publish(program / "candidate_wrapper.py", wrapper, 0o444),
             "submission.py": io.publish(program / "submission.py",
                                        (VERBOSE_CHILD if kind == "verbose" else FAILURE_CHILD).encode(), 0o444)}
    raw = json.dumps({"schema": "meg-frozen-program/v1", "files": files},
                     sort_keys=True, separators=(",", ":")).encode()
    files["PROGRAM.json"] = io.publish(program / "PROGRAM.json", raw, 0o444)
    data_files = {"INPUT.json": io.publish(data / "INPUT.json",
                  b'{"schema":"generated-diagnostic-input/v1","contains_original_data":false}\n', 0o444)}
    program.chmod(0o555); data.chmod(0o555)
    launcher = "#!/bin/sh\nexec " + shlex.quote(sys.executable) + " -I -S -B " + shlex.quote(str(HERE / "fixture_cli.py")) + ' "$@"\n'
    io.publish(root / "fixture-launcher", launcher.encode(), 0o555)
    return files, data_files


def run_phase(kind, root, io, transport, daemon_type):
    vendor = transport._vendor()
    root.mkdir(mode=0o700)
    io.root = root
    for name in ("control", "quarantine", "candidate-output"):
        (root / name).mkdir(mode=0o700)
    image = "sha256:" + "7" * 64
    phase = "generated-" + kind + "-A-fold-00"
    program_root = root / "programme"
    files, input_files = prepare_inputs(root, kind, transport, io)
    mounts = {"/program": {"path": str(program_root), "kind": "directory", "purpose": "program", "files": files},
              "/input": {"path": str(root / "input"), "kind": "directory", "purpose": "input",
                         "files": input_files}}
    exposure = {"schema": "osl_transport_exposure_v1", "role": "A", "image": image,
                "source": files["PROGRAM.json"], "command": list(transport.COMMAND),
                "mounts": vendor.bounds.mount_identity(mounts), "approved_image_inventory_sha256": "8" * 64,
                "boundary_audit": pin(b"generated observations only, no native authority"), "role_boundary_verified": True}
    exposure_pin = io.write("EXPOSURE.generated.json", exposure)
    resources = {"setup_seconds": 15, "producer_seconds": 10, "capture_seconds": 2, "cleanup_seconds": 10,
                 "memory_bytes": 134217728, "cpu_nanos": 1000000000, "pids": 16, "scratch_bytes": 4096,
                 "max_files": 2, "max_directories": 1, "max_file_bytes": 4096, "max_output_bytes": 8192,
                 "manifest_bytes": 4096, "max_cli_calls": 64, "max_cli_bytes": 2097152,
                 "inventory_bytes": 4096, "source_read_bytes": 4194304, "host_write_bytes": PROVIDER_WRITE}
    request = transport.make_request("generated-" + kind, "A", 0, image, files["PROGRAM.json"],
                                     exposure_pin, resources, START, DEADLINE)
    need(request["phase_id"] == phase, "Current generated method identity")
    endpoint = root / "fixture.sock"
    wrapper = program_root / "candidate_wrapper.py"
    config = {"socket": str(endpoint), "wrapper_source": str(wrapper), "wrapper_pin": files[wrapper.name],
              "wrapper_paths": {"request": str(root / "control" / phase / "REQUEST.json"),
                                "program": str(program_root / "submission.py"), "input": str(root / "input"),
                                "output": str(root / "candidate-output"), "python": sys.executable}}
    io.write("FIXTURE_CONFIG.json", config, 8192)
    diagnostic_path = root / "control" / phase / "PRODUCER_DIAGNOSTICS.json"
    daemon = daemon_type(endpoint, image, diagnostic_path, DEADLINE, root / "candidate-output")
    identities, fds, signal_calls, connection_paths = [], [], [], []

    def identity(pid, end, account_read, reserve_read):
        need(time.monotonic() < end, "Original gated identity clock")
        pgid, sid = os.getpgid(pid), os.getsid(pid)
        need(type(pid) is int and pid > 1 and pid == pgid == sid, "Actual fresh PID/session/group")
        token = {"schema": "osl_linux_process_identity_v1", "pid": pid, "pgid": pgid, "session_id": sid,
                 "uid": os.geteuid(), "start_time_ticks": 1, "boot_id": "00000000-0000-4000-8000-000000000001"}
        identities.append(token)
        return token

    def pidfd(pid, flags):
        need(flags == 0 and type(pid) is int, "Explicit disposable pidfd observation seam")
        fd = os.open(os.devnull, os.O_RDONLY); fds.append(fd); return fd

    def no_signal(*args, **kwargs):
        signal_calls.append(True)
        raise RuntimeError("No emulated Linux signal authority")

    class EndpointSocket:
        """Only AF_UNIX pathname spelling changes; wire IO stays real."""
        def __init__(self, family, kind):
            need(family == socket.AF_UNIX and kind == socket.SOCK_STREAM, "Exact generated archive socket family")
            self.sock = socket.socket(family, kind)
        def __getattr__(self, name): return getattr(self.sock, name)
        def connect(self, address):
            need(address == str(endpoint), "No off-endpoint archive connection")
            connection_paths.append(address)
            previous = Path.cwd()
            try:
                os.chdir(endpoint.parent)
                self.sock.connect(endpoint.name)
            finally: os.chdir(previous)

    archive_socket = types.SimpleNamespace(socket=EndpointSocket, AF_UNIX=socket.AF_UNIX, SOCK_STREAM=socket.SOCK_STREAM)
    daemon.start()
    try:
        with patch.dict(os.environ, {"MEG_DIAGNOSTIC_FIXTURE_CONFIG": str(root / "FIXTURE_CONFIG.json")}), \
             patch.object(vendor.engine, "process_identity", identity), \
             patch.object(os, "pidfd_open", pidfd, create=True), \
             patch.object(signal, "pidfd_send_signal", no_signal, create=True), \
             patch.object(vendor.archive, "socket", archive_socket):
            provider = vendor.Provider(root / "control", root / "quarantine", root / "fixture-launcher", endpoint,
                                       transport.VENDOR_PIN, {exposure_pin["sha256"]: str(root / "EXPOSURE.generated.json")},
                                       resources["source_read_bytes"], PROVIDER_WRITE)
            result = provider.execute_phase(request, mounts, DEADLINE, lambda *_: None)
    finally: daemon.close()
    receipt = result["receipt"]
    expected_code = 0 if kind == "verbose" else 1
    need(receipt["natural_exit"] == {"Status": "exited", "Running": False, "Dead": False, "Pid": 0,
                                    "ExitCode": expected_code, "OOMKilled": False}, "Exact actual wrapper exit joined to generated inspect")
    need(receipt["exit_observation_error"] is None and receipt["deadline_exceeded"] is False,
         "No hidden clock or exit-observation failure")
    need(receipt["all_native_resources_closed"] is True and receipt["cli_reaped"] is True,
         "Real Provider closure for generated resources")
    rows = receipt["command_metadata"]
    attached = [row for row in rows if row["phase"] == "producer_start"]
    need(len(attached) == 1 and type(attached[0]["returncode"]) is int and attached[0]["returncode"] == expected_code,
         "One actual attached command with exact exit")
    need(all(row["client_reaped"] is True and row["cleanup_complete"] is True and
             row["owned_group_absence_observed"] is True for row in rows), "Every actual CLI reaped and group absent")
    need(len(rows) == len(identities) <= 64 and not signal_calls, "No fictitious signal cleanup")
    for fd in set(fds):
        try: os.fstat(fd)
        except OSError as error: need(error.errno == errno.EBADF, "Disposable identity fd closed")
        else: need(False, "Identity descriptor leaked")
    desc = receipt["producer_diagnostic"]
    need(desc["path"] == str(diagnostic_path) and desc["trusted_private_only"] is True,
         "Private diagnostic descriptor only")
    document = json.loads(io.read(diagnostic_path, desc["pin"], 16384))
    need(stat.S_IMODE(diagnostic_path.lstat().st_mode) == 0o600, "Diagnostic remains private")
    need(document["complete_streams"] is True and document["candidate_output_artifact"] is False,
         "Complete private attached streams")
    raw_streams, stream_pins = {}, {}
    for name in ("stdout", "stderr"):
        declared = document["streams"][name]
        raw = base64.b64decode(declared["base64"], validate=True)
        stream_pins[name] = {k: declared[k] for k in ("bytes", "sha256")}
        need(pin(raw) == stream_pins[name], "Exact bounded stream descriptor")
        raw_streams[name] = raw
    capture = document["capture"]
    need(capture["stdout_eof"] is True and capture["stderr_eof"] is True and capture["overflow"] is False and
         type(capture["returncode"]) is int and capture["returncode"] == expected_code and
         capture["client_reaped"] is True and capture["owned_group_absence_observed"] is True and
         capture["cleanup_before_original_cutoff"] is True, "Real engine bounded EOF and cleanup")
    need(capture["stream_bytes_observed"] == capture["retained_bytes"] == sum(p["bytes"] for p in stream_pins.values()) <= 4096,
         "Exact attached stream byte count")
    need(len(daemon.wrapper_reports) == 1 and daemon.wrapper_reports[0] == {
        "kind": "wrapper_exit", "exit_code": expected_code, "error_type": None if kind == "verbose" else "SystemExit",
        "actual_main_called": True}, "Actual production main executed once")
    need(not daemon.errors and all(not values for values in daemon.resources.values()) and len(daemon.removals) == 3 and
         all(v["private_diagnostic_already_present"] is True for v in daemon.removals),
         "Actual persistence precedes all generated resource removals")
    need(len(receipt["retired_resources"]) == 3 and all(v["closed"] is True and v["absence_observed"] is True and
         v["creation_outcome_unknown"] is False for v in receipt["retired_resources"]), "No unknown resource creation passed")
    wrapper_summary = None
    if kind == "verbose":
        need(receipt["status"] == "captured" and receipt["error"] is None and receipt["producer_closed_before_capture"] is True,
             "Verbose success remains valid through unchanged Provider")
        need(raw_streams == {"stdout": b"", "stderr": b""}, "Successful child logs are not forwarded")
        expected = transport.validate_closed_receipt(receipt, request, mounts, DEADLINE)
        expected_body = VERBOSE_RESULT
        need(expected == pin(expected_body), "Strict consumer accepts exact generated result")
        captured = root / "quarantine" / phase / "RESULT.json"
        need(io.read(captured, expected, 4096) == expected_body, "Actual archive capture preserves result bytes")
        candidate = root / "candidate-output"
        quarantine = root / "quarantine" / phase
        need({p.name for p in candidate.iterdir()} == {"RESULT.json", "OUTPUTS.json"} and
             {p.name for p in quarantine.iterdir()} == {"RESULT.json", "OUTPUTS.json"},
             "Complete success output consists of exactly result and manifest")
        for name in ("RESULT.json", "OUTPUTS.json"):
            expected_file = receipt["output_inventory"]["files"][name]
            original_bytes = io.read(candidate / name, expected_file, 4096)
            captured_bytes = io.read(quarantine / name, expected_file, 4096)
            need(original_bytes == captured_bytes, "Both complete output files preserved unchanged")
        manifest = json.loads(io.read(quarantine / "OUTPUTS.json",
                                     receipt["output_inventory"]["files"]["OUTPUTS.json"], 4096))
        need(manifest == {"schema": "osl_transport_output_manifest_v1", "phase_id": phase,
                          "request_sha256": pin(vendor.engine.encoded(request))["sha256"],
                          "files": {"RESULT.json": pin(expected_body)}},
             "Exact current-request complete success manifest")

        need(set(daemon.archive_names) == {"RESULT.json", "OUTPUTS.json"} and len(connection_paths) == 2 and
             daemon.inventory_calls == 2, "Actual bounded archive path and paired inventory used")
    else:
        need(receipt["status"] == "failed" and receipt["error"] is not None and receipt["output_inventory"] is None,
             "Failing child remains ungraded")
        need(raw_streams["stdout"] == b"" and 0 < len(raw_streams["stderr"]) <= 3584,
             "Only bounded private wrapper failure envelope forwarded")
        envelope = json.loads(raw_streams["stderr"])
        need(envelope["schema"] == "meg_private_wrapper_diagnostics_v1", "Actual wrapper diagnostic schema")
        wrapper_summary = validate_failure_envelope(envelope)
        refused = False
        try: transport.validate_closed_receipt(receipt, request, mounts, DEADLINE)
        except ValueError: refused = True
        need(refused, "Unchanged consumer refuses failed receipt")
        need(not list((root / "candidate-output").iterdir()) and not list((root / "quarantine" / phase).iterdir()) and
             not daemon.archive_names and not connection_paths, "Failure exports no candidate or archive artifact")
    counters = result["final_transport_counters"]
    need(counters["write_reserved_bytes"] <= PROVIDER_WRITE and counters["read_bytes"] <= 4194304,
         "Unchanged prospective Provider accounting")
    io.write("PRIVATE_OBSERVATIONS.json", {"schema": "meg-generated-verbose-control-private/v1", "method": kind,
        "commands": daemon.commands, "removals": daemon.removals, "wrapper_reports": daemon.wrapper_reports,
        "actual_cli_pids": [row["pid"] for row in identities], "signal_calls": len(signal_calls),
        "archive_names": daemon.archive_names, "provider_receipt_pin": result["receipt_pin"]}, 12288)
    return {"method": kind, "status": "passed", "provider_status": receipt["status"], "exit_code": expected_code,
            "private_diagnostic_pin": desc["pin"], "stream_pins": stream_pins, "wrapper_summary": wrapper_summary,
            "cli_processes": len(rows), "all_cli_reaped": True, "generated_resources_retired": 3,
            "actual_archive_files": len(daemon.archive_names), "provider_counters": counters}


def validate_failure_envelope(envelope):
    streams = envelope["streams"]
    need(type(envelope["child_returncode"]) is int and envelope["child_returncode"] == 1, "Exact failed child returncode")
    trace = base64.b64decode(envelope["wrapper_traceback_base64"], validate=True)
    need(type(envelope["wrapper_traceback_bytes"]) is int and len(trace) == envelope["wrapper_traceback_bytes"] <= 768 and
         b"Candidate must exit successfully" in trace and envelope["diagnostic_only"] is True and envelope["candidate_artifact"] is False,
         "Actual bounded private wrapper traceback")
    result = {}
    for name in ("stdout", "stderr"):
        row = streams[name]
        prefix = base64.b64decode(row["prefix_base64"], validate=True)
        need(type(row["observed_bytes"]) is int and row["observed_bytes"] >= len(prefix) and
             type(row["retained_bytes"]) is int and row["retained_bytes"] == len(prefix) <= 512 and
             type(row["truncated"]) is bool and row["truncated"] == (row["observed_bytes"] > len(prefix)) and
             type(row["eof"]) is bool and row["counter_saturated"] is False, "Typed bounded child prefix observations")
        need(("GENERATED_CHILD_" + name.upper()).encode() in prefix, "Real child marker retained privately")
        if name == "stderr": need(b"Traceback" in prefix, "Real failing child traceback retained")
        result[name] = {k: row[k] for k in ("observed_bytes", "retained_bytes", "truncated", "eof")}
    return result



class DiagnosticRegressionTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        global START, DEADLINE
        START = time.monotonic()
        DEADLINE = START + 100
        cls.results = []
        cls.transport = load_source(PAIRED / "transport.py", "portable_diagnostic_transport")
        cls.fixtures = load_source(HERE / "fixtures.py", "portable_diagnostic_fixtures")
        cls.artifacts = None
        if "ARTIFACT_DIR" in os.environ:
            path = Path(os.environ["ARTIFACT_DIR"])
            need(path.is_absolute() and path.parent.is_dir() and path.resolve() == path,
                 "ARTIFACT_DIR is an absent canonical absolute leaf with existing parent")
            path.mkdir(mode=0o700)
            cls.artifacts = path

    @classmethod
    def tearDownClass(cls):
        if cls.artifacts is not None:
            report = {"schema": "meg-portable-diagnostic-controls/v1", "methods": 2,
                      "passed": len(cls.results) == 2 and all(r["status"] == "passed" for r in cls.results),
                      "results": cls.results, "native_isolation_qualified": False,
                      "scientific_qualification": False, "raw_diagnostics_exported": False}
            raw = encoded(report)
            need(len(raw) <= 16384, "Bounded aggregate-only artifact")
            fd = os.open(cls.artifacts / "RESULT.json", os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
            with os.fdopen(fd, "wb") as stream:
                stream.write(raw); stream.flush(); os.fsync(stream.fileno())

    def exercise(self, kind):
        scratch = Path(tempfile.mkdtemp(prefix="meg-diagnostics-")).resolve()
        root = scratch / "phase"
        io = IO(root)
        try:
            result = run_phase(kind, root, io, self.transport, self.fixtures.FixtureDaemon)
            files = [p for p in scratch.rglob("*") if p.is_file()]
            total = sum(p.stat().st_size for p in files)
            need(len(files) <= 192 and total <= 196608, "Finite generated phase file/byte census")
            result.update(generated_files=len(files), generated_bytes=total,
                          fixture_read_bytes=io.read_bytes, fixture_write_bytes=io.write_bytes)
            # Only this uniquely created generated tree is removed. Successful
            # aggregate admission also requires completed scratch cleanup.
            for directory, names, _ in os.walk(scratch):
                Path(directory).chmod(0o700)
                for name in names:
                    child = Path(directory) / name
                    need(not child.is_symlink(), "Generated cleanup never follows directory links")
            shutil.rmtree(scratch)
            self.results.append(result)
        except BaseException:
            self.results.append({"method": kind, "status": "failed", "generated_prefix_retained": scratch.exists()})
            raise

    def test_verbose_success_preserves_complete_outputs(self):
        self.exercise("verbose")

    def test_failure_retains_bounded_private_diagnostics(self):
        self.exercise("failure")


if __name__ == "__main__":
    unittest.main()
