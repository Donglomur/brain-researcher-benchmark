"""Generated manifest-consistency controls; no retinal arrays or model execution.

The wrapper controls substitute the scientific runtime after input preflight.
They test completion/failure reporting, not a scientific fit or numerical parity.
"""
import copy
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import sys
import tempfile
from types import ModuleType, SimpleNamespace
import unittest
from unittest.mock import patch
import zipfile

HERE = Path(__file__).resolve().parent
COMPONENT = HERE.parent


def source_module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


loading = source_module('generated_input_loading', COMPONENT / 'source_loading.py')
with patch.dict(sys.modules, {'source_loading': loading}):
    wrapper = source_module('generated_full_fit_wrapper', COMPONENT / 'full_fit.py')


class InputCommitmentTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix='jaxley-input-commitments-')
        self.addCleanup(self.temporary.cleanup)
        self.base = Path(self.temporary.name).resolve()
        self.inputs = self.base / 'inputs'
        (self.inputs / 'morphologies').mkdir(parents=True)
        # Preflight inspects ZIP membership and commitments, not NPY payloads.
        # These explicitly generated byte strings cannot be scientific inputs.
        packet = io.BytesIO()
        with zipfile.ZipFile(packet, 'w', compression=zipfile.ZIP_STORED) as archive:
            for name in sorted(loading.ARRAY_NAMES):
                archive.writestr(name + '.npy', b'generated preflight fixture only')
        (self.inputs / 'model_arrays.npz').write_bytes(packet.getvalue())
        metadata = {key: None for key in loading.META_FIELDS}
        metadata.update(test_targets_included=False,
                        arrays={key: {} for key in sorted(loading.ARRAY_NAMES)})
        (self.inputs / 'model_metadata.json').write_text(json.dumps(metadata))
        (self.inputs / 'morphologies/20161028_1.swc').write_text('# generated morphology sentinel\n')
        self.manifest_path = self.inputs / 'INPUT_FILES.json'
        self.manifest = {'schema': 'jaxley-streamed-fit-input-files-v1', 'files': {}}
        for name in ('model_arrays.npz', 'model_metadata.json', 'morphologies/20161028_1.swc'):
            self.refresh_pin(name)
        self.write_manifest()
        self.start_root, self.start_manifest = loading.input_paths(self.manifest_path)

    def refresh_pin(self, name):
        raw = (self.inputs / name).read_bytes()
        self.manifest['files'][name] = {'bytes': len(raw), 'sha256': hashlib.sha256(raw).hexdigest()}

    def write_manifest(self):
        self.manifest_path.write_text(json.dumps(self.manifest, sort_keys=True))

    def recheck(self):
        loading.reauthenticate_inputs(self.manifest_path, self.start_root, self.start_manifest)

    def replace_coherently(self, name):
        path = self.inputs / name
        if name.endswith('.json'):
            data = json.loads(path.read_text())
            data['source_preprocessing'] = 'generated replacement'
            path.write_text(json.dumps(data))
        elif name.endswith('.npz'):
            packet = io.BytesIO()
            with zipfile.ZipFile(packet, 'w', compression=zipfile.ZIP_STORED) as archive:
                for member in sorted(loading.ARRAY_NAMES):
                    archive.writestr(member + '.npy', b'coherent replacement preflight fixture')
            path.write_bytes(packet.getvalue())
        else:
            path.write_text('# coherently replaced morphology sentinel\n')
        self.refresh_pin(name)
        self.write_manifest()

    def test_unchanged_input_commitments_pass(self):
        self.recheck()

    def test_json_key_reordering_preserves_commitments(self):
        reordered = {'files': dict(reversed(list(self.manifest['files'].items()))),
                     'schema': self.manifest['schema']}
        self.manifest_path.write_text(json.dumps(reordered, indent=3))
        self.recheck()

    def test_coherent_replacement_of_each_input_is_rejected(self):
        for name in self.manifest['files']:
            with self.subTest(name=name):
                before = (self.inputs / name).read_bytes()
                self.replace_coherently(name)
                # The previous final check accepted each of these replacements:
                # they are independently self-consistent input manifests.
                root, updated = loading.input_paths(self.manifest_path)
                self.assertEqual(root, self.start_root)
                self.assertNotEqual(updated, self.start_manifest)
                with self.assertRaisesRegex(ValueError, 'initial file commitments'):
                    self.recheck()
                (self.inputs / name).write_bytes(before)
                self.manifest = copy.deepcopy(self.start_manifest)
                self.write_manifest()

    def test_uncommitted_file_change_still_fails_digest_check(self):
        path = self.inputs / 'morphologies/20161028_1.swc'
        original = path.read_bytes()
        path.write_bytes(b'!' + original[1:])
        with self.assertRaisesRegex(ValueError, 'file digest pin'):
            self.recheck()

    def test_same_manifest_from_another_root_is_rejected(self):
        with self.assertRaisesRegex(ValueError, 'initial file commitments'):
            loading.reauthenticate_inputs(self.manifest_path, self.base / 'another-input-root',
                                          self.start_manifest)

    def generated_wrapper(self, mutate):
        """Exercise the real wrapper's final check and durable result path."""
        stats = {'training_singletons_completed': 255885, 'completed_original_gradient_batches': 1008,
                 'validation_singletons_completed': 63987, 'completed_original_validation_batches': 63,
                 'test_singletons_completed': 128, 'last_global_mean_denominator': 153,
                 'last_training_batch_completed_rows': 153, 'last_validation_batch_completed_rows': 999}
        snapshot = {'generated_parameter': 1.0}
        canonical = lambda obj: json.dumps(obj, sort_keys=True).encode()
        matrix = lambda: SimpleNamespace(tolist=lambda: [[0.]])
        class GeneratedRuntime:
            def __init__(self, *args, **kwargs):
                self.stats = stats.copy()
                self.updates, self.history = 1008, [{'generated': True}] * 21
                self.codec = SimpleNamespace(encode_tree=lambda value, *args, **kwargs: value,
                                             canonical=canonical, tree_witness=lambda *args: {})
                self.np, self.tree_util = None, None
                self.selected_snapshot_sha256 = hashlib.sha256(canonical(snapshot)).hexdigest()
                self.opt, self.optimizer_states, self.states = snapshot, {}, {}
                self.initial_context, self.initial_model_state, self.rng = {}, {}, {}
                self.selected_predictions = matrix()
                self.policy = SimpleNamespace(POLICY_SHA256='0' * 64)
            def model_state_unchanged(self):
                pass
        runtime_module = ModuleType('fit_runtime')
        runtime_module.FitRuntime = GeneratedRuntime
        loop_module = ModuleType('fit_loop')
        def generated_fit(_runtime):
            if mutate:
                self.replace_coherently('morphologies/20161028_1.swc')
            return {'best_snapshot': snapshot, 'best_epoch_zero_based': 0,
                    'best_validation_mean': 0.0, 'test_predictions': matrix()}
        loop_module.run_production = generated_fit
        # Only the source wrapper and real input preflight/publication run. The
        # numerical loader, scientific runtime and full fit are explicit doubles.
        arrays = {'currents': SimpleNamespace(shape=(15360, 287), flags=SimpleNamespace(writeable=True))}
        meta = {'cell_id': 'generated', 'identity_sha256': '0' * 64,
                'splits': {'val': [1], 'test': [2]}, 'sites': []}
        model = SimpleNamespace(load_packet=lambda *args: (arrays, meta))
        output = self.base / 'output'
        with patch.object(wrapper, 'runtime_requirements', return_value={'schema': 'generated-runtime'}), \
             patch.object(wrapper, 'load_frozen_sources', return_value=model), \
             patch.dict(sys.modules, {'fit_runtime': runtime_module, 'fit_loop': loop_module}):
            if mutate:
                with self.assertRaisesRegex(ValueError, 'initial file commitments'):
                    wrapper.run(self.manifest_path, output, 30.)
            else:
                wrapper.run(self.manifest_path, output, 30.)
        return json.loads((output / 'RESULT.json').read_text())

    def test_wrapper_unchanged_inputs_reach_completion_path(self):
        report = self.generated_wrapper(mutate=False)
        self.assertTrue(report['complete'])
        self.assertEqual(report['input_files'], self.start_manifest['files'])
        self.assertEqual(report['scientific_status'], 'UNQUALIFIED')

    def test_wrapper_coherent_replacement_keeps_failed_partial_result(self):
        report = self.generated_wrapper(mutate=True)
        self.assertFalse(report['complete'])
        self.assertEqual(report['status'], 'FAILED_OR_PARTIAL_NOT_A_COMPLETE_FIT')
        self.assertEqual(report['error_type'], 'ValueError')
        self.assertIn('initial file commitments', report['error'])
        self.assertEqual(report['optimizer_updates'], 1008)
        self.assertEqual(report['validation_checks'], 21)


if __name__ == '__main__':
    unittest.main(verbosity=2)
