"""Reference solution for ERRMON-001.

Reproduce the **error-related frontocentral negativity (the ERN)** in the ERP CORE
Flankers task (subject 001), quantified as the **mean error-minus-correct amplitude at
electrode FCz in the 0-100 ms window**, with an average reference and a 0.1-30 Hz
band-pass.

The one choice the brief leaves un-cued is **which event the epochs are time-locked to**.
The recording carries both stimulus markers (the flanker arrays) and response markers (the
left/right button presses). The error-related frontocentral negativity is generated by the
motor/monitoring system at the moment of the erroneous **response**, not the stimulus, and
the button presses occur a variable ~400 ms (206-1438 ms here) after the stimulus. Averaging
epochs that are time-locked to the **response** therefore reveals the full error-vs-correct
negativity; time-locking to the **stimulus** (the naive choice) smears it across the reaction
-time jitter and all but cancels it.

Everything else is pinned (subject 001; an error trial = the pressed hand does not match the
target arrow's direction; FCz; average reference over the 30 scalp electrodes; 0.1-30 Hz
band-pass; a pre-event baseline; the mean amplitude in the 0-100 ms window), so only the
time-locking choice moves the number.

Validated (MNE 1.12.1, ERP CORE Flankers subject 001, 400 trials, 54 errors / 346 correct):
    ERN, response-locked (correct)   : -5.9 uV   <-- reported here
    error-minus-correct, stimulus-locked (naive), same 0-100 ms window: -0.6 uV
The correct value is robust (-5.5 to -6.2 uV across 0.1-15/20/30/40 Hz low-pass and
pre-event baseline windows, average reference); the stimulus-locked value stays near 0 uV
(|diff| <= ~3.9 uV across stimulus-locked windows).
"""
import json
import os
import sys
import warnings
from pathlib import Path

import numpy as np

warnings.filterwarnings("ignore")

OUT = Path(os.environ.get("OUTPUT_DIR", "/app/output"))
OUT.mkdir(parents=True, exist_ok=True)

L_FREQ, H_FREQ = 0.1, 30.0
BASELINE = (-0.2, 0.0)
WIN = (0.0, 0.1)           # measurement window, s, relative to the epoch's event
# ERP CORE annotation codes
RESP_LEFT, RESP_RIGHT = 1, 2
STIM_TARGET_LEFT = {3, 5}   # stimulus/{compatible,incompatible}/target_left
STIM_TARGET_RIGHT = {4, 6}  # stimulus/{compatible,incompatible}/target_right


def fail(reason):
    (OUT / "run_metadata.json").write_text(json.dumps(
        {"status": "failed_precondition", "reason": reason, "dataset_id": "erp_core_flankers"}, indent=2))
    (OUT / "ern.json").write_text(json.dumps({"status": "failed_precondition", "reason": reason}))
    (OUT / "findings.md").write_text(f"# Failed precondition\n\n{reason}\n")
    sys.stderr.write(reason + "\n")
    sys.exit(1)


try:
    import mne
    mne.set_log_level("ERROR")
except Exception as e:  # pragma: no cover
    fail(f"mne import failed: {e}")


def raw_path():
    env = os.environ.get("ERP_CORE_DIR")
    cands = []
    if env:
        cands.append(Path(env))
    try:
        cands.append(Path(mne.datasets.erp_core.data_path()))
    except Exception as e:
        fail(f"could not fetch the ERP CORE dataset: {e}")
    for base in cands:
        hits = sorted(base.glob("**/*Flankers_eeg.fif"))
        if hits:
            return hits[0]
    fail("could not locate the ERP CORE Flankers subject-001 recording")


def pair_trials(events):
    """Pair each stimulus with the next button press; label error if the pressed hand does
    not match the target arrow. Returns (stim_sample, resp_sample, is_error) rows."""
    rows = []
    for i, e in enumerate(events):
        code = e[2]
        if code in STIM_TARGET_LEFT or code in STIM_TARGET_RIGHT:
            j = i + 1
            while j < len(events) and events[j, 2] not in (RESP_LEFT, RESP_RIGHT):
                j += 1
            if j < len(events):
                correct_hand = RESP_LEFT if code in STIM_TARGET_LEFT else RESP_RIGHT
                is_error = int(events[j, 2] != correct_hand)
                rows.append((int(e[0]), int(events[j, 0]), is_error))
    return rows


def mean_amp_diff(raw, rows, anchor, win=WIN, base=BASELINE):
    ev = np.array([[rs if anchor == "response" else ss, 0, (2 if err else 1)]
                   for ss, rs, err in rows], dtype=int)
    ep = mne.Epochs(raw, ev, event_id={"correct": 1, "error": 2},
                    tmin=min(base[0], win[0]) - 0.05, tmax=max(base[1], win[1]) + 0.05,
                    baseline=base, picks=["FCz"], preload=True, verbose=False)
    err_ev = ep["error"].average()
    cor_ev = ep["correct"].average()
    t = err_ev.times
    m = (t >= win[0]) & (t <= win[1])
    diff = 1e6 * float(err_ev.data[0, m].mean() - cor_ev.data[0, m].mean())
    return diff, 1e6 * float(err_ev.data[0, m].mean()), 1e6 * float(cor_ev.data[0, m].mean()), \
        len(ep["error"]), len(ep["correct"])


try:
    raw = mne.io.read_raw_fif(str(raw_path()), preload=True, verbose=False)
    # tag the peripheral channels as EOG so they are excluded from the average reference
    eog = {c: "eog" for c in ("HEOG_left", "HEOG_right", "VEOG_lower") if c in raw.ch_names}
    if eog:
        raw.set_channel_types(eog)
    if "FCz" not in raw.ch_names:
        fail("electrode FCz not present in the recording")
    events, _ = mne.events_from_annotations(raw, verbose=False)
    rows = pair_trials(events)
    if not rows:
        fail("no stimulus-response trials could be paired")
    raw.filter(L_FREQ, H_FREQ, picks="eeg", verbose=False)
    raw.set_eeg_reference("average", projection=False, verbose=False)
    ern, err_amp, cor_amp, n_err, n_cor = mean_amp_diff(raw, rows, "response")
    stim_diff, _, _, _, _ = mean_amp_diff(raw, rows, "stimulus")
except SystemExit:
    raise
except Exception as e:
    fail(f"could not compute the error-related frontocentral negativity: {e}")

(OUT / "ern.json").write_text(json.dumps({
    "ern_amplitude_uv": ern,
    "electrode": "FCz",
    "measure": "mean error-minus-correct amplitude, 0-100 ms",
    "reference": "average (30 scalp electrodes)",
    "bandpass_hz": [L_FREQ, H_FREQ],
    "window_ms": [0, 100],
    "n_error_trials": int(n_err),
    "n_correct_trials": int(n_cor),
    "error_trial_amplitude_uv": err_amp,
    "correct_trial_amplitude_uv": cor_amp,
    "stimulus_locked_diff_uv_for_reference": stim_diff,
}, indent=2))

(OUT / "run_metadata.json").write_text(json.dumps({
    "status": "ok",
    "dataset_id": "erp_core_flankers (ERP CORE, Flankers task, subject 001)",
    "file": "ERP-CORE_Subject-001_Task-Flankers_eeg.fif",
    "trial_definition": "error = pressed hand != target arrow direction",
    "n_error_trials": int(n_err),
    "n_correct_trials": int(n_cor),
    "electrode": "FCz",
    "reference": "average (30 scalp electrodes; EOG excluded)",
    "bandpass_hz": [L_FREQ, H_FREQ],
    "baseline_ms": [int(BASELINE[0] * 1000), int(BASELINE[1] * 1000)],
    "measurement_window_ms": [0, 100],
    "measure": "mean error-minus-correct amplitude at FCz",
}, indent=2))

(OUT / "findings.md").write_text(f"""# ERRMON-001 - error-related frontocentral negativity (ERP CORE Flankers, subject 001)

In the ERP CORE Flankers task (subject 001; {n_err} error trials vs {n_cor} correct trials),
electrode **FCz** shows a pronounced negativity on error trials. Measured as the **mean
error-minus-correct amplitude in the 0-100 ms window** (average reference, 0.1-30 Hz
band-pass), the error-related frontocentral negativity is **{ern:.1f} uV** (error trials
{err_amp:.1f} uV, correct trials {cor_amp:.1f} uV).

This error-related negativity is generated at the time of the erroneous button press: the
responses occur a variable interval after the flanker array, so the negativity emerges when
the epochs are aligned to the **response**. Aligning the same epochs to the stimulus instead
leaves an error-minus-correct difference of only {stim_diff:.1f} uV in the same window, because
the response-time jitter smears the effect. The value above ({ern:.1f} uV) is the error-related
frontocentral negativity.
""")
print(f"OK: ERN (response-aligned)={ern:.2f} uV | stimulus-aligned(naive)={stim_diff:.2f} uV | "
      f"n_err={n_err} n_cor={n_cor}")
