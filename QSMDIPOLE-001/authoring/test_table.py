@pytest.mark.parametrize("label", q.LABELS)
def test_each_roi_is_bound_to_its_saved_map(mechanical_output, small_reference, label):
    path = mechanical_output / "nuclei_susceptibility.csv"
    rows = list(csv.DictReader(path.open()))
