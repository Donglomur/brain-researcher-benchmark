def write_output(output, reference, chi=None):
    output.mkdir(parents=True, exist_ok=True)
    chi = reference["map"] if chi is None else chi
    np.save(output / "susceptibility_ppm.npy", chi)
    rows = [{"label": label, "n_voxels": count, "susceptibility_ppb": median}
            for label, (count, median) in q.roi_summary(chi, reference["roi"]).items()]
    write_rows(output, rows)
    metadata = dict(reference["stats"]["metadata_contract"], status="ok",
                    n_brain_voxels=int(reference["mask"].sum()), n_rois_reported=6,
                    brain_mask_mean_ppb=float(np.mean(chi[reference["mask"]], dtype=np.float64) * 1000))
    (output / "run_metadata.json").write_text(json.dumps(metadata))
    (output / "findings.md").write_text("Numerical fixture; no biological inference.")
    return output


def write_rows(output, rows, columns=None):
    with (output / "nuclei_susceptibility.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=columns or list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


