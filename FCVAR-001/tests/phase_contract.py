"""Shared-phase multivariate surrogate and acquisition identity contract."""
import numpy as np
VERSION="fcvar-subject-tr-phase-v2"

def read_tr(header):
    value=float(header.get_zooms()[3])
    unit=header.get_xyzt_units()[1]
    assert unit in {"sec","msec","usec"}, "unknown acquisition TR units"
    value*= {"sec":1.0,"msec":1e-3,"usec":1e-6}[unit]
    assert np.isfinite(value) and 0.1<value<10
    return value

def surrogate(ts, phase):
    ts=np.asarray(ts,float);phase=np.asarray(phase,float)
    assert ts.ndim==2 and np.isfinite(ts).all()
    assert phase.shape==(len(ts)//2+1,) and np.isfinite(phase).all()
    assert phase[0]==0 and (len(ts)%2!=0 or phase[-1]==0)
    return np.fft.irfft(np.fft.rfft(ts,axis=0)*np.exp(1j*phase)[:,None],n=len(ts),axis=0)

def edge_sd(ts,window,step=3):
    iu=np.triu_indices(ts.shape[1],1)
    edges=[np.arctanh(np.clip(np.corrcoef(ts[s:s+window].T),-.999,.999))[iu]
           for s in range(0,len(ts)-window+1,step)]
    assert len(edges)>=2
    return float(np.std(edges,axis=0,ddof=1).mean())

def check_subject(data,reference,row):
    assert str(reference["schema_version"])==VERSION, "genuine TR/ID-correct v2 reference required"
    assert str(data["subject_id"])==str(reference["subject_id"])
    assert str(data["site"])==str(reference["site"])
    assert np.isclose(float(data["tr_sec"]),float(reference["tr_sec"]),atol=1e-7)
    ts=np.asarray(data["roi_signals"])
    assert np.allclose(ts,reference["roi_signals"],atol=1e-6,rtol=1e-5)
    results={}
    for window in (20,30,44):
        phase=np.asarray(data[f"phase_w{window}"])
        assert phase.shape==(50,len(ts)//2+1)
        expected_rng=np.random.default_rng(int(data["seed"])+int(str(data["subject_id"]))+window)
        expected=expected_rng.uniform(0,2*np.pi,size=phase.shape)
        expected[:,0]=0
        if len(ts)%2==0:expected[:,-1]=0
        assert np.allclose(phase,expected,atol=1e-12), "phase not generated by declared common-phase protocol"
        values=np.array([edge_sd(surrogate(ts,p),window) for p in phase])
        observed=edge_sd(ts,window)
        assert abs(float(row[f"mean_edge_sd_w{window}"])-observed)<=1e-5
        assert abs(float(row[f"mean_edge_sd_null_w{window}"])-float(values.mean()))<=1e-5
        results[str(window)]={"ratio":observed/values.mean(),
                             "p":(1+np.count_nonzero(values>=observed))/51}
    return results
