def close_tree(root,names,end,cap):
    need(len(names)==len(set(names)) and 0<len(names)<=400,'complete finite output inventory')
    files={};dirs=set()
    for name in names:
        need(time.monotonic()<end,'original host work deadline')
        f=ordinary(root/relative(name));st=f.lstat();need(st.st_nlink==1 and f.is_file() and 0<st.st_size<=cap,'bounded regular generated artifact')
        d={'bytes':st.st_size,'sha256':hash_file(f,st.st_size,end)}
        capture(f,d,cap,retain=False)
        fd=os.open(f,os.O_RDONLY|os.O_NOFOLLOW)
        try:os.fsync(fd)
        finally:os.close(fd)
        files[name]=d
        q=f.parent
        while q!=root:dirs.add(q);q=q.parent
    # Exact tree membership also excludes unclaimed partials or extra files.
    actual=[]
    for base,sub,leaves in os.walk(root,followlinks=False):
        need(len(actual)+len(leaves)<=400 and len(sub)<=64,'bounded generated tree')
        for n in sub:need(not (Path(base)/n).is_symlink(),'ordinary generated directory')
        actual.extend((Path(base)/n).relative_to(root).as_posix() for n in leaves)
    need(set(actual)==set(names),'no undeclared generated output')
    for d in sorted(dirs,key=lambda q:len(q.parts),reverse=True):sync_dir(d)
    sync_dir(root);sync_dir(root.parent);need(time.monotonic()<end,'durable generated tree before original deadline')
    return files


def hash_file(path,size,end):
    h=hashlib.sha256();f=None
    try:
        f=path.open('rb');left=size
        while left:
            need(time.monotonic()<end,'original hash deadline');b=f.read(min(left,1048576));need(b,'complete generated byte stream');left-=len(b);h.update(b)
        need(not f.read(1),'exact generated EOF')
    finally:
        if f is not None:f.close()
    return h.hexdigest()


